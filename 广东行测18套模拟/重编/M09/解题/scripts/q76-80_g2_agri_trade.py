# -*- coding: utf-8 -*-
"""M09 第76—80题（2020年上半年我国农产品进出口）核算、易错路径与本组自洽检查。
出口额按编排的材料修订读作“351.5亿美元”。饼图与表格按原卷裁图逐项核对，与转写一致。"""

total, imp, exp_ = 1159.0, 807.5, 351.5
r_imp, r_exp = 0.132, -0.038
imp_share = {'亚洲': 18.9, '非洲': 3.0, '欧洲': 18.8, '南美洲': 31.5, '北美洲': 14.9, '大洋洲': 12.7}
exp_share = {'亚洲': 65.3, '非洲': 4.5, '欧洲': 14.7, '南美洲': 3.3, '北美洲': 10.1, '大洋洲': 2.0}
r_europe = 0.284
asia_exp = 229.7
# 类别：进口额、进口增速、出口额、出口增速
cats = {'谷物': (33.9, 25.2, 5.5, -7.0), '食用蔬菜': (9.6, 4.0, 44.9, -4.8), '禽类产品': (17.0, 66.0, 11.7, -24.5),
        '畜类产品': (222.0, 43.2, 12.4, -16.6), '水、海产品': (65.8, -6.4, 48.7, -19.6),
        '饮料、酒及醋': (21.3, -23.9, 10.1, 3.3), '食用水果及坚果': (68.0, 10.2, 22.9, 24.4),
        '咖啡、茶、马黛茶及调味香料': (5.3, 20.1, 20.4, 15.5)}


def nearest(x, opts):
    return min(opts, key=lambda k: abs(opts[k] - x))


print('== 自洽检查 ==')
print('进口＋出口＝%.1f，与总额1159.0一致：%s（出口单位应为亿美元）' % (imp + exp_, abs(imp + exp_ - total) < 1e-9))
print('进口饼图合计%.1f%%，出口饼图合计%.1f%%（四舍五入误差）' % (sum(imp_share.values()), sum(exp_share.values())))
print('亚洲出口：351.5×65.3%%＝%.1f，文字229.7（229.7÷351.5＝%.2f%%）' % (exp_ * 0.653, asia_exp / exp_ * 100))
print('食用蔬菜＋水、海产品出口＝%.1f（文字93.6），占%.2f%%（文字26.6%%）' % (44.9 + 48.7, (44.9 + 48.7) / exp_ * 100))
print('出口最多两类：', sorted(cats, key=lambda k: -cats[k][2])[:2])
inc_live = 222.0 - 222.0 / 1.432
inc_imp = imp - imp / (1 + r_imp)
print('畜类进口增量%.2f÷进口总增量%.2f＝%.1f%%（文字“超7成”）' % (inc_live, inc_imp, inc_live / inc_imp * 100))
print('欧洲增速28.4%为各洲最大（文字），饼图不涉及增速，无可比项')

print('\n== 第76题 ==')
o76 = {'A': 2.5, 'B': 5.0, 'C': 7.5, 'D': 10.0}
bi, be = imp / (1 + r_imp), exp_ / (1 + r_exp)
g = total / (bi + be) - 1
print('进口基期%.2f、出口基期%.2f（约%.2f∶1），合计%.2f，增速%.3f%% → %s' % (bi, be, bi / be, bi + be, g * 100, nearest(g * 100, o76)))
print('按2∶1加权：(2×13.2−3.8)÷3＝%.2f%%' % ((2 * 13.2 - 3.8) / 3))
sa = (13.2 - 3.8) / 2
print('简单平均%.2f%% → %s（易错）' % (sa, nearest(sa, o76)))

print('\n== 第77题 ==')
o77 = {'A': 6, 'B': 8, 'C': 10, 'D': 12}
dec = 48.7 * 0.196 / (1 - 0.196)
print('48.7×19.6%%÷80.4%%＝%.2f → %s；1/n法 48.7÷4＝%.2f' % (dec, nearest(dec, o77), 48.7 / 4))
wrong = 48.7 * 0.196
print('现期×降幅＝%.2f → %s（易错）' % (wrong, nearest(wrong, o77)))

print('\n== 第78题 ==')
for k in ('食用蔬菜', '禽类产品', '饮料、酒及醋', '咖啡、茶、马黛茶及调味香料'):
    i, ri, e, re = cats[k]
    bi_, be_ = i / (1 + ri / 100), e / (1 + re / 100)
    print('%s：2020年合计%.1f；2019年 %.2f＋%.2f＝%.2f' % (k, i + e, bi_, be_, bi_ + be_))

print('\n== 第79题 ==')
o79 = {'A': 13.3, 'B': 16.6, 'C': 18.8, 'D': 21.1}
s = 18.8 * (1 + r_imp) / (1 + r_europe)
print('18.8%%×1.132÷1.284＝%.3f%% → %s' % (s, nearest(s, o79)))
w = 18.8 * (1 + r_europe) / (1 + r_imp)
print('公式颠倒18.8%%×1.284÷1.132＝%.2f%% → %s（易错）；直接读2020年18.8%% → C（易错）' % (w, nearest(w, o79)))

print('\n== 第80题 ==')
print('A 222.0÷33.9＝%.3f；33.9×6＝%.1f＜222 → 对' % (222.0 / 33.9, 33.9 * 6))
print('B 亚洲进口807.5×18.9%%＝%.2f＜亚洲出口229.7 → 对' % (imp * 0.189))
print('C 160÷807.5＝%.2f%%；各洲进口额：' % (160 / imp * 100),
      {k: round(imp * v / 100, 1) for k, v in imp_share.items()}, '→ 只有南美洲超160，对')
print('   粗估亚洲18.9%%≈20%%：807.5×20%%＝%.1f＞160 → 会误判C错（易错）' % (imp * 0.20))
s_exp = sum(v[2] for v in cats.values())
print('D 表中出口合计%.1f，占%.2f%% → 约一半而非30%%，错' % (s_exp, s_exp / exp_ * 100))
print('   出口30%%为%.1f亿美元，仅两类已93.6、再加水果22.9即%.1f' % (exp_ * 0.3, 93.6 + 22.9))
