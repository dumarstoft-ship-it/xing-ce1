"""M09 第86—89题（我国电信业务收入）核算、易错路径与本组自洽检查；第90题饼图见 q90_pie_angles.py。
折线图、柱状图按原卷裁图逐个数据标签核对，与转写一致。"""

T2022 = 15800.0  # 1.58万亿元
rate = {2018: 0.029, 2019: 0.005, 2020: 0.039, 2021: 0.081, 2022: 0.080}
mob = {2018: 5984, 2019: 6096, 2020: 6204, 2021: 6381, 2022: 6397}
new = {2018: 1084, 2019: 1374, 2020: 1737, 2021: 2372, 2022: 3072}
tot = {2022: T2022}
for y in (2021, 2020, 2019, 2018):
    tot[y] = tot[y + 1] / (1 + rate[y + 1])


def nearest(x, opts):
    return min(opts, key=lambda k: abs(opts[k] - x))


print('== 自洽检查 ==')
print('由1.58万亿元与各年增速倒推电信业务收入：', {y: round(v, 1) for y, v in sorted(tot.items())})
print('较2018年增加%.1f亿元（文字“超2800亿元”）' % (T2022 - tot[2018]))
print('移动数据流量增速6397÷6381−1＝%.3f%%（文字0.3%%）；占比6397÷15800＝%.2f%%（文字40.5%%）' % (
    (6397 / 6381 - 1) * 100, 6397 / T2022 * 100))
print('新兴业务占比：2022年%.2f%%（文字19.4%%）；2021年%.2f%%（文字16.1%%，差约0.1个百分点，源于1.58万亿元、8%%均为约数）' % (
    3072 / T2022 * 100, 2372 / tot[2021] * 100))
print('若按16.1%%反推2021年电信业务收入：2372÷16.1%%＝%.0f亿元' % (2372 / 0.161))
print('新兴业务2022年增速%.1f%%，介于四个分项增速11.5%%—118.2%%之间' % ((3072 / 2372 - 1) * 100))

print('\n== 第86题 ==')
o86 = {'A': 1.1, 'B': 1.2, 'C': 1.3, 'D': 1.4}
prod = 1.005 * 1.039 * 1.081 * 1.08
print('15800÷(15800−2800)＝%.4f；增速连乘＝%.4f → %s' % (T2022 / 13000, prod, nearest(prod, o86)))
w = prod * 1.029
print('误把2018年2.9%%也乘入：%.4f → %s（易错）' % (w, nearest(w, o86)))

print('\n== 第87题 ==')
s21, s22 = mob[2021] / tot[2021], mob[2022] / T2022
print('2021年占比%.2f%%，2022年%.2f%%，变化%.2f个百分点' % (s21 * 100, s22 * 100, (s22 - s21) * 100))
print('公式：40.5%%×(0.3%%−8%%)÷1.003＝%.2f个百分点 → 减少约3个百分点（B）' % (40.5 * (0.003 - 0.08) / 1.003))
print('按16.1%%反推的2021年总额：%.2f%% − 40.5%% → 仍约减少3个百分点' % (mob[2021] / (2372 / 0.161) * 100))

print('\n== 第88题 ==')
o88 = {'A': 30, 'B': 40, 'C': 50, 'D': 60}
inc_t = T2022 * 0.08 / 1.08
v = 700 / inc_t * 100
print('新兴增量%d；电信增量15800×8%%÷1.08＝%.1f；比重%.2f%% → %s' % (3072 - 2372, inc_t, v, nearest(v, o88)))
print('易错：新兴自身增速700÷2372＝%.2f%% → %s；省去÷1.08：700÷1264＝%.2f%%（介于50%%与60%%之间）' % (
    700 / 2372 * 100, nearest(700 / 2372 * 100, o88), 700 / 1264 * 100))
print('按16.1%%反推的2021年总额算：700÷(15800−%.0f)＝%.1f%% → 仍为D' % (2372 / 0.161, 700 / (T2022 - 2372 / 0.161) * 100))

print('\n== 第89题 ==')
ratio = 3072 / 1084
print('A 3072÷1084＝%.3f；1.2^4＝%.4f；年均增速%.2f%% → 对' % (ratio, 1.2 ** 4, (ratio ** 0.25 - 1) * 100))
print('B 2019年0.5%＜1% → 错')
print('C (6397−5984)÷4＝%.2f亿元，约100而非1000 → 错' % ((6397 - 5984) / 4))
print('D (118.2%%+58%%)÷2＝%.1f%%，即简单平均；无分项收入，推不出 → 错' % ((118.2 + 58) / 2))
