# -*- coding: utf-8 -*-
"""M09 第81—85题（广东医疗卫生资源）核算、易错路径与本组自洽检查。三张图按原卷裁图逐个数据标签核对，与转写一致。"""

inst = {2009: 4.43, 2010: 4.49, 2011: 4.59, 2012: 4.66, 2013: 4.79, 2014: 4.81, 2015: 4.84, 2016: 4.91}  # 万个
beds = {2012: (35.5, 27.3, 5.2), 2013: (37.8, 29.4, 5.2), 2014: (40.6, 32.0, 5.3), 2015: (43.6, 34.5, 5.5),
        2016: (46.5, 37.2, 5.7)}  # 万张：医疗卫生机构、医院、卫生院
tech = {2012: (20.0, 19.9, 52.0), 2013: (21.8, 21.1, 55.6), 2014: (23.4, 21.7, 58.4), 2015: (25.4, 22.9, 62.0),
        2016: (28.4, 24.4, 66.8)}  # 万人：注册护士、执业（助理）医师、卫生技术人员


def nearest(x, opts):
    return min(opts, key=lambda k: abs(opts[k] - x))


print('== 自洽检查 ==')
print('文字2016年：机构4.91万个、床位46.5/37.2/5.7、卫技66.8、医师24.4、护士28.4，与图一致：',
      inst[2016] == 4.91 and beds[2016] == (46.5, 37.2, 5.7) and tech[2016] == (28.4, 24.4, 66.8))
print('医护比 28.4÷24.4＝%.3f（文字1∶1.16）' % (28.4 / 24.4))
print('医院＋卫生院 ≤ 机构床位：', {y: round(b[1] + b[2], 1) for y, b in beds.items()}, all(b[1] + b[2] <= b[0] for b in beds.values()))
print('护士＋医师 ≤ 卫技：', all(t[0] + t[1] <= t[2] for t in tech.values()))

print('\n== 第81题 ==')
for y in range(2010, 2017):
    print('%d年：增量%.2f，增长率%.2f%%' % (y, inst[y] - inst[y - 1], (inst[y] / inst[y - 1] - 1) * 100))
print('选项年份中2013年最高；数量最多的是2016年（%.2f万个，易错D）' % inst[2016])

print('\n== 第82题 ==')
o82 = {'A': 0.9, 'B': 1.1, 'C': 1.7, 'D': 2.1}
v = (24.4 - 19.9) / 4
print('(24.4−19.9)÷4＝%.3f → %s；按2013—2016年三次增长 (24.4−21.1)÷3＝%.3f → %s' % (
    v, nearest(v, o82), (24.4 - 21.1) / 3, nearest((24.4 - 21.1) / 3, o82)))
print('易错：误读护士 (28.4−20)÷4＝%.2f → %s；除以5 4.5÷5＝%.2f → %s' % (
    (28.4 - 20) / 4, nearest((28.4 - 20) / 4, o82), 4.5 / 5, nearest(4.5 / 5, o82)))

print('\n== 第83题 ==')
o83 = {'A': 1.2, 'B': 1.5, 'C': 2.0, 'D': 2.3}
a16, a12 = 46.5 / 4.91, 35.5 / 4.66
print('2016年%.3f张/个，2012年%.3f张/个，倍数%.4f → %s' % (a16, a12, a16 / a12, nearest(a16 / a12, o83)))
print('床位比%.4f ÷ 机构比%.4f；只比床位总数得%.3f（口径错，仍近A）' % (46.5 / 35.5, 4.91 / 4.66, 46.5 / 35.5))

print('\n== 第84题 ==')
o84 = {'A': 38.2, 'B': 40.1, 'C': 42.5, 'D': 48.7}
for y, (n, d, t) in tech.items():
    print('%d年 护士占比%.3f%%' % (y, n / t * 100))
for y in range(2013, 2017):
    print('%d年 护士增速%.2f%% vs 卫技增速%.2f%%' % (y, (tech[y][0] / tech[y - 1][0] - 1) * 100, (tech[y][2] / tech[y - 1][2] - 1) * 100))
v = 28.4 / 66.8 * 100
print('最高2016年%.2f%% → %s；误算2012年%.2f%% → %s；2014年%.2f%% → %s' % (
    v, nearest(v, o84), 20 / 52 * 100, nearest(20 / 52 * 100, o84), 23.4 / 58.4 * 100, nearest(23.4 / 58.4 * 100, o84)))

print('\n== 第85题 ==')
print('A 4.91÷4.43＝%.3f → 错' % (4.91 / 4.43))
print('B 医院床位占比：', {y: round(b[1] / b[0] * 100, 2) for y, b in beds.items()}, '；46.5×0.8＝%.1f → 2016年恰为80%%，错' % (46.5 * 0.8))
print('C 卫技只有2012—2016年，2009—2011年无数据 → 推不出；2012—2016年每机构卫技：',
      {y: round(t[2] / inst[y], 2) for y, t in tech.items()})
print('D 护士−医师：', {y: round(t[0] - t[1], 1) for y, t in tech.items()}, '→ 2016年最大，对')
