"""第71题：2022年下半年中国空调产量。
2022年下半年 = 2022年1-12月累计 - 2022年1-6月累计；
2022年1-6月不在表中，由2023年1-6月累计14060万台、累计增速16.6%反推。"""
from q71_75_group1_data import cum, base
opts = {'A': 10189, 'B': 11236, 'C': 12058, 'D': 13131}
h1_2022 = base(*cum['2023-06'])
h2_2022 = cum['2022-12'][0] - h1_2022
print(f'2022年1-6月 = 14060/1.166 = {h1_2022:.2f}')
print(f'2022年下半年 = 22247 - {h1_2022:.2f} = {h2_2022:.2f}')
best = min(opts, key=lambda k: abs(opts[k]-h2_2022)); print('最接近:', best, opts[best])
# 估算精度：选项间最小相对差
vals = sorted(opts.values()); print('相邻选项相对差:', [round(b/a-1, 3) for a, b in zip(vals, vals[1:])])
# 估算：14060/1.166 ≈ 12060 -> 22247-12060 = 10187
print('估算 14060/1.166 ≈', round(14060/1.166, -1), '-> 22247 -', round(14060/1.166, -1), '=', 22247-round(14060/1.166, -1))
# 易错核对
print('误把反推出的上半年当答案:', round(h1_2022, 1), '-> C')
print('误用2023年1-6月未换算:', 22247-14060)
print('误用 14060×(1-16.6%):', round(22247-14060*(1-0.166), 1))
