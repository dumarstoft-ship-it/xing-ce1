"""第4组（第86—90题）共用数据与自洽检查：移动游戏实际销售收入、产品类型占比、移动游戏占游戏市场比重。"""
rev = {2020: 2096.76, 2021: 2255.38, 2022: 1930.58, 2023: 2268.60}   # 亿元（2018、2019年未给）
g = {2018: 15.36, 2019: 18.03, 2020: 32.61, 2021: 7.57, 2022: -14.40, 2023: 17.51}  # %
types2023 = {'角色扮演类': 29.55, '多人在线移动竞技类': 17.01, '射击类': 14.70, '策略类': 6.64, '棋牌类': 4.67,
             '捕鱼游戏': 4.42, '休闲类': 4.32, '卡牌类': 3.61, '自走棋': 2.59, '其他': 12.48}
mob_share = {2018: 62.47, 2019: 68.48, 2020: 75.24, 2021: 76.06, 2022: 72.61, 2023: 74.88}  # %

if __name__ == '__main__':
    for y in (2021, 2022, 2023):
        print(f'{y}年增速：由收入算 {100*(rev[y]/rev[y-1]-1):.3f}% vs 图中 {g[y]}%')
    print('产品类型占比合计：', round(sum(types2023.values()), 2), '%')
    r2019 = rev[2020]/(1+g[2020]/100); r2018 = r2019/(1+g[2019]/100)
    allrev = {2018: r2018, 2019: r2019, **rev}
    print(f'反推：2019年 {r2019:.2f}，2018年 {r2018:.2f}')
    print('游戏市场总收入（移动/占比）：', {y: round(v/(mob_share[y]/100), 2) for y, v in allrev.items()})
