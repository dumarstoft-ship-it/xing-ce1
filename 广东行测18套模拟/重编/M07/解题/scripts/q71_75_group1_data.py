def base(v, r):
    return v / (1 + r / 100)

if __name__ == '__main__':
    # 2022年各月当月产量（相邻累计相减）
    keys22 = ['2022-08', '2022-09', '2022-10', '2022-11', '2022-12']
    for a, b in zip(keys22, keys22[1:]):
        print(f'2022年{b[-2:]}月当月产量 = {cum[b][0]} - {cum[a][0]} = {cum[b][0]-cum[a][0]}')
    # 2023年累计值反推2022年同期累计值
    print()
    b22 = {}
    for k in ['2023-02', '2023-03', '2023-04', '2023-05', '2023-06', '2023-07']:
        v, r = cum[k]
        b22[k] = base(v, r)
        print(f'2022年1-{int(k[-2:])}月(由2023年反推) = {v}/(1+{r}%) = {b22[k]:.1f}')
    print(f"由反推值接表中2022年1-8月：8月当月 = 15722 - {b22['2023-07']:.1f} = {15722-b22['2023-07']:.1f}")
    print()
    ks = ['2023-02', '2023-03', '2023-04', '2023-05', '2023-06', '2023-07']
    for a, b in zip(ks, ks[1:]):
        cur = cum[b][0] - cum[a][0]
        old = b22[b] - b22[a]
