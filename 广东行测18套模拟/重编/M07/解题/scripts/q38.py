# 第38题：甲先出发30分钟，乙出发后又过30分钟两车在C相遇，BC=20km，甲速=1.3乙速，求AB
from fractions import Fraction as F
# 甲行驶1小时：AB+20；乙行驶0.5小时：AB-20
# AB+20 = 1.3v*1, AB-20 = v*0.5
v = F(40) / (F(13, 10) - F(1, 2))
AB = v / 2 + 20
print("乙速", v, "AB", AB, "检验", AB + 20 == F(13, 10) * v)
# 枚举选项检验
for name, s in {"A": 30, "B": 35, "C": 40, "D": 45}.items():
    v_yi = (s - 20) / F(1, 2)
    ok = (s + 20) == F(13, 10) * v_yi
    print(name, s, "乙速", v_yi, "甲路程", s + 20, "1.3乙速*1h", F(13, 10) * v_yi, ok)
