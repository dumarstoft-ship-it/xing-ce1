"""第72题：2022年10月空调产量环比。
当月产量 = 本月累计 - 上月累计；环比 = 10月产量/9月产量 - 1。"""
from q71_75_group1_data import cum
sep = cum['2022-09'][0] - cum['2022-08'][0]
octo = cum['2022-10'][0] - cum['2022-09'][0]
r = octo / sep - 1
print(f'9月产量 = 17492-15722 = {sep}；10月产量 = 18960-17492 = {octo}')
print(f'环比 = {octo}/{sep} - 1 = {100*r:.2f}%  -> 下降约17%（D）')
print(f'估算：减少 {sep-octo}，{sep-octo}/{sep} = {100*(sep-octo)/sep:.1f}%')
# 易错核对
print('方向看反（302/1770记成增长）-> 增长17%（B）；用10月作分母：', f'{100*(sep/octo-1):.1f}%（无对应选项）')
print('把累计产量当当月产量直接比：18960/17492-1 =', f'{100*(18960/17492-1):.2f}%', '-> 增长方向，最接近A（增长7%）')
