"""第84题：2025年一季度第二产业增加值占GDP比重（基期比重）= A/B × (1+b)/(1+a)。"""
from q81_85_group3_data import gdp, gdp_g, ind
A, a = ind['第二产业']
cur = A / gdp
base = cur * (1 + gdp_g/100) / (1 + a/100)
print(f'现期比重 12410.95/34950.34 = {100*cur:.3f}%')
print(f'基期比重 = {100*cur:.3f}% × 1.046/1.047 = {100*base:.3f}%  -> C(35.5%)')
print(f'直接算：(12410.95/1.047)/(34950.34/1.046) = {100*(A/(1+a/100))/(gdp/(1+gdp_g/100)):.3f}%')
print('两增速只差0.1个百分点，基期比重与现期比重相差不到0.05个百分点；四个选项相差3个百分点以上，算现期比重即可定C')
