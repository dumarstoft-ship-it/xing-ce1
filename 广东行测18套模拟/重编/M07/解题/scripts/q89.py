print(f'2022年 = 1930.58/72.61% = {tot22:.2f}；2021年 = 2255.38/76.06% = {tot21:.2f}；变化 {tot22-tot21:.2f} -> 减少不到500亿元，A')
print(f'估算：1930.58/0.7261≈2659，2255.38/0.7606≈2965，差约-306；离500相差很远，取三位有效数字即可')
