"""第2组（第76—80题）共用数据与自洽检查：规模以上互联网企业业务收入、利润。"""
# 2024年累计：期末月 -> (业务收入 亿元, 利润总额 亿元, 利润同比 %)
y24 = {2: (2463, 169.7, 6.5), 3: (3840, 278.9, -15.3), 4: (5547, 384.9, -19.7),
       5: (6861, 521.4, -12.8), 6: (8676, 743.7, 1.9)}
# 业务收入累计同比增速 %
rev_g23 = {2: -3.9, 3: 1.6, 4: 3.3, 5: 2.8, 6: 2.6, 7: 2.8, 8: 2.6, 9: 3.4, 10: 5.9, 11: 6.1, 12: 6.8}
rev_g24 = {2: 7.6, 3: 8.4, 4: 3.7, 5: 5.0, 6: 5.6}
# 2024年上半年分地区：收入、同比增速（东部、中部由“低于/高于全国”换算）
nat_g = rev_g24[6]
regions = {'东部': (None, nat_g - 0.4), '中部': (408.8, nat_g + 6.4), '西部': (525.4, 4.6), '东北': (20.8, -2.1)}

if __name__ == '__main__':
    print('2023年同期累计值（由2024年反推）：')
    r23, p23 = {}, {}
    for m, (r, p, pg) in y24.items():
        r23[m] = r / (1 + rev_g24[m]/100); p23[m] = p / (1 + pg/100)
        print(f'  1-{m}月 收入 {r23[m]:.1f}  利润 {p23[m]:.1f}  利润率 {100*p23[m]/r23[m]:.2f}%（2024年 {100*p/r:.2f}%）')
    print('当月值（相邻累计相减）：')
    for m in range(3, 7):
        print(f'  {m}月：2024年 收入 {y24[m][0]-y24[m-1][0]} 利润 {y24[m][1]-y24[m-1][1]:.1f}；'
              f'2023年 收入 {r23[m]-r23[m-1]:.1f} 利润 {p23[m]-p23[m-1]:.1f}')
    # 分地区：东部收入由合计减出
    east = 8676 - 408.8 - 525.4 - 20.8
    print(f'\n东部收入 = 8676-408.8-525.4-20.8 = {east:.1f}，增速 {regions["东部"][1]:.1f}%；中部增速 {regions["中部"][1]:.1f}%')
    bases = {'东部': east/(1+regions['东部'][1]/100)}
    for k in ['中部', '西部', '东北']:
        v, g = regions[k]; bases[k] = v/(1+g/100)
    tot_base = sum(bases.values())
    print('各地区上年同期：', {k: round(v, 1) for k, v in bases.items()}, '合计', round(tot_base, 1))
    print(f'全国上年同期 8676/1.056 = {8676/1.056:.1f}；按地区合计推出的全国增速 = {100*(8676/tot_base-1):.2f}%（材料 5.6%）')
