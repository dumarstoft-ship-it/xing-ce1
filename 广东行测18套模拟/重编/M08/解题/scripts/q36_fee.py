"""M08 第36题：40户，原价1200元/户，打9折后每户再减固定补贴x，实缴共41000元，求x"""
from fractions import Fraction as F
opts = {'A': 50, 'B': 55, 'C': 60, 'D': 65}
x = F(1200)*F(9, 10) - F(41000, 40)
print('先打折后补贴: x =', x)
ans = [k for k, v in opts.items() if 40*(1200*F(9, 10) - v) == 41000]
assert ans == ['B']; print('答案', ans)
# 另一种顺序（先减补贴再打9折）不得整数选项
y = 1200 - F(41000, 40)/F(9, 10)
print('若先减补贴再打折: x =', y, float(y), '(不在选项中)')
# 错误思路：按原价总额算 (48000-41000)/40
print('按原价总额误算:', (48000-41000)/40)
