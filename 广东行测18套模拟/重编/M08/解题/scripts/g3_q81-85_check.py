# -*- coding: utf-8 -*-
"""M08 资料第3组（第81—85题）：H省农林牧渔业主要产品产量。数据检查 + 第81—85题核算。"""

T = {  # 万吨：2021, 2022, 2023
    "蔬菜": (588.92, 605.43, 632.90),
    "水果": (525.52, 563.47, 592.69),
    "香蕉": (116.02, 114.82, 117.72),
    "菠萝": (45.08, 51.61, 55.97),
    "芒果": (82.99, 84.59, 91.04),
    "龙眼": (6.07, 6.12, 6.17),
    "柑橘橙柚": (14.11, 16.75, 15.66),
    "橡胶": (35.22, 31.45, 34.79),
    "胡椒": (4.23, 3.67, 3.72),
    "槟榔": (27.88, 29.48, 31.62),
    "猪肉": (30.52, 33.86, 42.12),
    "禽肉": (32.29, 31.48, 30.29),
    "禽蛋产品": (5.02, 5.92, 7.11),
    "海水产品": (130.29, 128.05, 130.62),
    "淡水产品": (36.68, 43.13, 46.62),
}
fruits = ["香蕉", "菠萝", "芒果", "龙眼", "柑橘橙柚"]

print("== 数据检查 ==")
for i, y in enumerate((2021, 2022, 2023)):
    s5 = sum(T[f][i] for f in fruits)
    print(f"{y} 五类水果合计 {s5:.2f} ≤ 水果 {T['水果'][i]} ? {s5 <= T['水果'][i]}；"
          f"水产品 = 海水+淡水 = {T['海水产品'][i] + T['淡水产品'][i]:.2f}")

print("\n== 第81题 ==")
v = T["蔬菜"]
g23 = v[2] / v[1] - 1
print(f"2023增速 = 632.90/605.43-1 = {g23:.4%}；2024 = 632.90×(1+{g23:.4%}) = {v[2]*(1+g23):.3f}")
print(f"等价：2024增量 = 2023增量27.47×(1+r) = {(v[2]-v[1])*(1+g23):.3f}")
print(f"误按增量不变：632.90+27.47 = {v[2]+(v[2]-v[1]):.2f}")
g22 = v[1] / v[0] - 1
print(f"误用2022增速 {g22:.3%}：{v[2]*(1+g22):.2f}")
print(f"误用两年总增速 {v[2]/v[0]-1:.3%}：{v[2]*v[2]/v[0]:.2f}；年均 {(v[2]/v[0])**0.5-1:.3%}：{v[2]*(v[2]/v[0])**0.5:.2f}")
for opt in (655, 658, 662, 690):
    print(f"  选项{opt}对应的2024增速 {opt/v[2]-1:.3%}")

print("\n== 第82题 ==")
w21 = T["海水产品"][0] + T["淡水产品"][0]
w22 = T["海水产品"][1] + T["淡水产品"][1]
w23 = T["海水产品"][2] + T["淡水产品"][2]
print(f"水产品：2021 {w21:.2f}，2022 {w22:.2f}，2023 {w23:.2f}")
print(f"2023比2021增长 {w23/w21-1:.3%}")
r1, r2 = w22 / w21 - 1, w23 / w22 - 1
print(f"间隔增长率核对：r1={r1:.3%}，r2={r2:.3%}，r1+r2+r1r2 = {r1+r2+r1*r2:.3%}")
print(f"只看海水 {T['海水产品'][2]/T['海水产品'][0]-1:.2%}，只看淡水 {T['淡水产品'][2]/T['淡水产品'][0]-1:.2%}，"
      f"误算2023同比 {r2:.2%}")

print("\n== 第83题 ==")
items = [("①橡胶", "橡胶"), ("②槟榔", "槟榔"), ("③猪肉", "猪肉"), ("④禽肉", "禽肉")]
ch = {lab: T[k][1] - T[k][0] for lab, k in items}
for lab, k in items:
    print(f"{lab}: {T[k][0]}→{T[k][1]} 变化 {ch[lab]:+.2f}，增速 {T[k][1]/T[k][0]-1:+.2%}")
by_abs = "".join(l[0] for l in sorted(ch, key=lambda l: -abs(ch[l])))
by_sign = "".join(l[0] for l in sorted(ch, key=lambda l: -ch[l]))
by_rate = "".join(l[0] for l in sorted(ch, key=lambda l: -abs(ch[l] / T[dict(items)[l]][0])))
print(f"按绝对值从大到小：{by_abs}；按带符号：{by_sign}；按增速绝对值：{by_rate}")
opts = {"A": "②④①③", "B": "①③④②", "C": "③①④②", "D": "①③②④"}
print("与选项相符：", [k for k, s in opts.items() if s == by_abs])

print("\n== 第84题 ==")
s5 = sum(T[f][2] for f in fruits)
print(f"2023五类合计 {s5:.2f} / {T['水果'][2]} = {s5/T['水果'][2]:.3%}")
print(f"45%界 {0.45*T['水果'][2]:.2f}，50%界 {0.5*T['水果'][2]:.2f}")

print("\n== 第85题 ==")
gt = [T["水果"][1] / T["水果"][0] - 1, T["水果"][2] / T["水果"][1] - 1]
print(f"水果总产量增速：2022 {gt[0]:.3%}，2023 {gt[1]:.3%}")
both = 0; only22 = 0; only23 = 0; prod_up_both = 0
for f in fruits:
    g = [T[f][1] / T[f][0] - 1, T[f][2] / T[f][1] - 1]
    sh = [T[f][i] / T["水果"][i] for i in range(3)]
    up = [sh[1] > sh[0], sh[2] > sh[1]]
    both += all(up); only22 += up[0]; only23 += up[1]
    prod_up_both += (g[0] > 0 and g[1] > 0)
    print(f"{f}: 增速 {g[0]:+.2%}/{g[1]:+.2%}；比重 {sh[0]:.3%}→{sh[1]:.3%}→{sh[2]:.3%}；比重上升 {up}")
print(f"两年比重均上升：{both} 类；只看2022：{only22} 类；只看2023：{only23} 类；两年产量均增长：{prod_up_both} 类")
