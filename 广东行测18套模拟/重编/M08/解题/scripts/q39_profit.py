"""M08 第39题：新品售价260、利润率30%；促销品亏损25%；各卖一件不赚不赔，求收入。"""
from fractions import Fraction as F
c1 = F(260)/F(13, 10); p1 = 260 - c1
c2 = p1 / F(1, 4)          # 促销品亏损额 = 成本×25% = 新品利润
s2 = c2 * F(3, 4)
print('新品成本', c1, '利润', p1, '促销品成本', c2, '售价', s2, '总收入', 260 + s2)
assert 260 + s2 == 440
# 枚举验证：促销品成本取整数，不赚不赔唯一
sols = [c for c in range(1, 2000) if p1 - F(c, 4) == 0]
print('满足不赚不赔的促销品成本:', sols)
print('误把促销品成本当售价: 260 +', c2, '=', 260 + c2)
