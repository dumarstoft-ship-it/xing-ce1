"""M08 第44题：靠墙长方形，栅栏围三边(两短一长)，长比短多30米；栅栏上每15米一盏灯共21盏且四个顶点都有灯。
改为正方形(长边不变，仍靠墙)，间距12米，四个顶点有灯，求灯数增加多少。枚举短边。"""
sols = []
for a in range(1, 500):
    b = a + 30
    L = 2*a + b
    if L % 15 == 0 and L//15 + 1 == 21 and a % 15 == 0 and b % 15 == 0:
        sols.append((a, b))
print('(短边, 长边):', sols); assert sols == [(90, 120)]
a, b = sols[0]
s = b; L2 = 3*s
assert s % 12 == 0
new = L2//12 + 1
print('正方形边长', s, '栅栏长', L2, '新灯数', new, '增加', new - 21)
assert new - 21 == 10
print('若误按闭合环路(不+1)计新灯数:', L2//12, '→ 增加', L2//12 - 21)
print('若原灯数按闭合(21段):', 21*15, '不是整段解 → 3a+30=315, a=95 非15倍数')
