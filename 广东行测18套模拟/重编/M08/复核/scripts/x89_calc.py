# 第89题：各项 2023 年比上年的增减量（万吨），增减量 = 现期 × r / (1 + r)
items = {}
# ① 石油：13050 万吨，+5.4%
items['①石油运量'] = 13050 * 0.054 / 1.054
# ② 其他铁路发送量：总量 50.35 亿吨 − 国家铁路 39.11 亿吨 = 11.24 亿吨，+3.9%
other = (50.35 - 39.11) * 10000
items['②其他铁路发送量'] = other * 0.039 / 1.039
# 交叉核对：总增量 0.51 亿吨 − 国家铁路增量
nat_inc = 39.11e4 * 0.002 / 1.002
print(f'②核对：0.51亿吨−国家铁路增量{nat_inc:.0f}万吨 = {5100 - nat_inc:.0f}万吨；按表 503535−498424 = {503535-498424} 万吨 → 其他铁路 {503535-498424-nat_inc:.0f} 万吨')
# ③ 粮食：6847 万吨，−8.0%
items['③粮食运量'] = 6847 * 0.080 / 0.920
# ④ 冶炼物资：90986 万吨，−5.3%
items['④冶炼物资运量'] = 90986 * 0.053 / 0.947
sign = {'①石油运量': 1, '②其他铁路发送量': 1, '③粮食运量': -1, '④冶炼物资运量': -1}
for k, v in items.items():
    print(f'{k}: {"增加" if sign[k] > 0 else "减少"} {v:.1f} 万吨')
print('按增减数量（绝对值）从多到少：', ''.join(k[0] for k, _ in sorted(items.items(), key=lambda kv: -kv[1])))
print('若按带符号增长量从高到低：', ''.join(k[0] for k, _ in sorted(items.items(), key=lambda kv: -sign[kv[0]] * kv[1])))
