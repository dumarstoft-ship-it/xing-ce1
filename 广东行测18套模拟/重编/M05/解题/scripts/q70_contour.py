"""M05 第70题：等高线地形图判读。

读图（题图放大到4~6倍核对，坐标为原图像素，x向右=东，y向下=南）：
  A：山顶，海拔670米（三角符号）；其外依次为600（未标注）、500（标注）闭合等高线；
  E：位于500米等高线外侧的那条等高线上，即400米；C 也在400米等高线上；
  等高距100米（400、300、200、100米均有标注）。
  小溪：从F西北方约400米等高线处起，向东南依次穿过300米（F点）、200米、100米等高线，
        各等高线在与小溪相交处都向上游（西北，海拔高处）弯曲，是山谷，与小溪位置相符。
  D：位于100米等高线向东南（低处）凸出的弯曲顶点，凸起内侧是200米等高线 -> 山脊。
  B：旁边是带短齿的陡崖符号（多条等高线在此重合）。

脚本计算：小溪各交点的流向方位角、E与A的气温差（气温垂直递减率约0.6℃/100米）。
"""
import math

# 小溪与等高线交点（像素坐标读数）和对应海拔
stream = [((235, 65), 400), ((285, 100), 300), ((329, 138), 200), ((367, 197), 100)]


def bearing(p, q):
    """从p到q的方位角（正北为0°，顺时针），图像y轴向下"""
    dx, dy = q[0] - p[0], -(q[1] - p[1])
    return math.degrees(math.atan2(dx, dy)) % 360


for (p, hp), (q, hq) in zip(stream, stream[1:]):
    assert hp > hq            # 顺流海拔降低
    b = bearing(p, q)
    print(f"{hp}m -> {hq}m: 方位角 {b:.0f}°（90°=正东，135°=东南，225°=西南）")
    assert 100 < b < 170      # 偏东南方向，不是西南（约225°）

overall = bearing(stream[0][0], stream[-1][0])
print(f"整体流向方位角 {overall:.0f}° -> 自西北流向东南；A项“自东北向西南”错误")

# 气温：E(400m) 与 A(670m)
hE, hA = 400, 670
dT = (hA - hE) * 0.6 / 100
print(f"E比A低{hA - hE}米，气温约高{dT:.2f}℃；C项“E处气温比A处低”错误")
assert hE < hA

# D：100米等高线在D处的弯曲方向。D=(465,262)，弯曲内侧（北侧）可见200米等高线约在(450,175)
D, inner200 = (465, 262), (450, 175)
assert inner200[1] < D[1]     # 200米线在D的北侧（凸起内侧），外侧（南侧）低于100米
print("D处等高线向海拔低处凸出 -> 山脊；B项“山谷”错误")
print("B处为陡崖，适宜攀岩 -> D项正确")
print("答案: D")
