"""M10 第66题：28℃蔗糖水加糖后完全溶解，放入冰箱后杯底析出少许晶体。判断①—④。
选项 A①② B①④ C②③ D②④
蔗糖溶解度（g/100g水，常用手册值）：0℃ 179.2，10℃ 190.5，20℃ 203.9，30℃ 219.5，40℃ 238.1。
用两种开局说明①“一定不是饱和溶液”不成立，再按选项组合判断。"""
sol = {0: 179.2, 10: 190.5, 20: 203.9, 30: 219.5, 40: 238.1}
def s(t):                                   # 线性插值
    ks = sorted(sol)
    for a, b in zip(ks, ks[1:]):
        if a <= t <= b:
            return sol[a] + (sol[b] - sol[a]) * (t - a) / (b - a)
s28, s4 = s(28), s(4)
print('28℃溶解度≈%.1f g，冰箱4℃溶解度≈%.1f g（每100g水）' % (s28, s4))
for sugar in (200.0, s28):                   # 情形一：不饱和；情形二：恰好饱和（仍是“完全溶解”）
    state = '恰好饱和' if abs(sugar - s28) < 1e-9 else '不饱和'
    crystal = max(0.0, sugar - s4)
    print('100g水溶%.1fg糖：28℃时%s，全部溶解；冷到4℃析出%.1fg，析出后溶液中溶质%.1fg（饱和）' % (sugar, state, crystal, sugar - crystal))
# ①：两种情形都与题述现象相符，故“一定不是饱和溶液”不成立
# ②：有晶体析出且与溶液共存 → 该温度下饱和，成立
# ③：析出晶体后溶液中溶质质量减少，不成立
# ④：析出的晶体是蔗糖，蒸发溶剂（蒸发结晶）也能得到蔗糖，成立
truth = {1: False, 2: True, 3: False, 4: True}
opts = {'A': (1, 2), 'B': (1, 4), 'C': (2, 3), 'D': (2, 4)}
ok = [k for k, v in opts.items() if all(truth[i] for i in v)]
print('答案：', ok)
assert ok == ['D']
