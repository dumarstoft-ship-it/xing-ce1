"""M10 第43题：边长10米的正方形，以两个相对顶点为圆心、边长为半径作两段四分之一圆弧，另有一条对角线。
题图读法（原卷2019年县级卷第30题，放大核对）：设左下顶点O(0,0)、右上顶点(10,10)。
  上方圆弧以左下顶点为圆心，下方圆弧以右上顶点为圆心；画出的对角线是左下—右上。
  阴影只在对角线一侧：上部是“正方形内、以左下顶点为圆心的圆外、且在对角线上方(y>x)”的部分，
  下部是“以右上顶点为圆心的圆外、且在对角线下方(y<x)”的部分；对角线另一侧的两个小角是空白。
选项 A 100−25π  B 200−35π  C 200−50π  D 100π−100"""
from math import pi
import numpy as np
N = 4000
xs = (np.arange(N) + 0.5) * 10 / N
X, Y = np.meshgrid(xs, xs)
up = (X ** 2 + Y ** 2 > 100) & (Y > X)
down = ((X - 10) ** 2 + (Y - 10) ** 2 > 100) & (Y < X)
area = (up.sum() + down.sum()) * (10 / N) ** 2
whole_corners = ((X ** 2 + Y ** 2 > 100).sum() + ((X - 10) ** 2 + (Y - 10) ** 2 > 100).sum()) * (10 / N) ** 2
opts = {'A': 100 - 25 * pi, 'B': 200 - 35 * pi, 'C': 200 - 50 * pi, 'D': 100 * pi - 100}
print('阴影面积（数值）%.4f' % area, {k: round(v, 4) for k, v in opts.items()})
print('若把两个角上的整块都当阴影：%.4f' % whole_corners)
assert abs(area - opts['A']) < 0.01 and abs(whole_corners - opts['C']) < 0.02
# 精确：上部 = 三角形(0,0)(0,10)(10,10)面积50 − 45°扇形(100π/8)
assert abs((50 - 100 * pi / 8) * 2 - opts['A']) < 1e-12
print('D项100π−100≈%.1f，大于正方形面积100，不可能；叶形（两扇形重叠）面积50π−100≈%.2f' % (opts['D'], 50 * pi - 100))
