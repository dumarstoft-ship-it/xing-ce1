print('== 本组自洽检查 ==')
for y, rows in T.items():
    for j, c in enumerate(cols):
        s = sum(rows[k][j] for k in ('高级', '一级', '二级', '三级', '未评'))
        assert s == rows['小计'][j], (y, c, s, rows['小计'][j])
    assert rows['小计'][0] == text_total[y] and rows['小计'][1] == text_female[y]
    for j, c in enumerate(cols[2:], start=2):
        assert rows['小计'][j] == text_age[c][y]
    for k, v in rows.items():
        assert v[1] <= v[0] and sum(v[2:]) <= v[0]
    for c in text_age_f:
        assert text_age_f[c][y] <= text_age[c][y]
