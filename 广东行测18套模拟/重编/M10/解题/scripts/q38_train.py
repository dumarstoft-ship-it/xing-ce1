"""M10 第38题：货车72km/h、客车108km/h同向，货车长=1.5×客车长，车尾平齐到车头平齐用20秒，求客车长。
选项 A160 B240 C400 D600"""
from fractions import Fraction as F
vf, vp = F(72 * 1000, 3600), F(108 * 1000, 3600)   # 20 m/s，30 m/s
t = 20
# 车尾平齐时，客车（较短）车头落后货车车头 (1.5L−L)；客车快，靠速度差追上这段距离
L = (vp - vf) * t / (F(3, 2) - 1)
print('速度差', vp - vf, 'm/s，追及距离', (vp - vf) * t, '米，客车长', L, '米，货车长', F(3, 2) * L, '米')
# 位置模拟：以车尾平齐时货车车尾为原点
def heads(t_, Lp):
    return vf * t_ + F(3, 2) * Lp, vp * t_ + Lp     # 货车车头、客车车头
for Lp in (160, 240, 400, 600):
    hf, hp = heads(20, F(Lp))
    print('客车长', Lp, '：20秒后两车车头相差', hf - hp, '米')
assert L == 400 and heads(20, L)[0] == heads(20, L)[1]
# 把倍数关系设反（设货车x、客车1.5x）：0.5x=200 → x=400，客车1.5x=600（D）
print('倍数设反时“客车长”=', F(3, 2) * ((vp - vf) * t / F(1, 2)))
