"""M11 第47题（GD2015-XJ-Q044）：数面（封闭区域）与笔画（奇点）。

按放大图逐图读出各交点的度数：拐角2度，T形点3度，十字交叉或两图形顶点相接4度；圆与三角形顶点相切处，
圆记为一条自环（贡献2度）。有界区域数 = E − V + 连通块数（欧拉公式）。
选项A按图细读：小三角形两腰接在上方正方形底边的两个点上（相距约5像素），底边接在下方两正方形内侧竖边上
（比两正方形顶边低约4像素），共6个T形点；若按“顶点恰好相接”读，则没有奇点。
选项C：三角形压在三个正方形上，被盖住的线不画，形成6个T形点。
"""
def info(name, degs, comps=1):
    V = len(degs); E = sum(degs) // 2
    faces = E - V + comps
    odd = sum(d % 2 for d in degs)
    one = comps == 1 and odd in (0, 2)
    print(f'{name}: 面 {faces}，奇点 {odd}，{"一笔画" if one else "不能一笔画"}')

info('图1 中间三角+三个小三角', [4, 4, 4] + [2] * 6)
info('图2 两圆相交', [4, 4])
info('图3 三角形+三个圆(顶点相切)', [4, 4, 4])
info('图4 两正方形相交', [4, 4] + [2] * 8)
info('A 按图细读', [3] * 6 + [2] * 10)
info('A 若顶点恰好相接', [4] * 3 + [2] * 10)
info('B 三长方形两两相交', [4] * 6 + [2] * 12)
info('C 三角形盖在三正方形上', [3] * 6 + [2] * 13)
info('D 三个分离正方形', [2] * 12, comps=3)
