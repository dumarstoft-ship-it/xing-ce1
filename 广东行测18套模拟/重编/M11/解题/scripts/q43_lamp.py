"""M11 第43题：身高1.6米，起初影长3.2米，向灯走1米后影长1.6米，求灯高。 选项 A2.6 B2.8 C3.2 D3.4
相似三角形：设起初人到灯的水平距离为d，1.6/H=3.2/(3.2+d)=1.6/(1.6+d−1)。"""
from fractions import Fraction as F
h = F(8, 5)
# 3.2/(3.2+d) = 1.6/(0.6+d) → d=2
d = (F(16, 5) * F(3, 5) - F(8, 5) * F(16, 5)) / (F(8, 5) - F(16, 5))
H = h * (F(16, 5) + d) / F(16, 5)
print('人到灯的水平距离', d, '米，灯高', H, '米 =', float(H))
assert d == 2 and H == F(13, 5) and h * (F(8, 5) + d - 1) / F(8, 5) == H
# 坐标验证：灯在(0,H)，人头顶在(x,h)，影端 = x·H/(H−h)
for x in (d, d - 1):
    print('人在距灯', x, '米处，影长', x * H / (H - h) - x)
