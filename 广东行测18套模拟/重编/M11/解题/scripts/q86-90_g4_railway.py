# -*- coding: utf-8 -*-
"""M11 第86—90题（GDXD2019-XC-M1，全国铁路营业里程）核算与本组自洽检查。
柱状图按原卷裁图 GDXD2019-XC-p11-i01.png 核对柱顶标注，与转写一致（纵轴无刻度数字，但柱高按比例）；
文字中的2.4%、56.7%、68.5%、3.3%在原卷第10页是嵌入小图，渲染后核对，转写无误。"""

yrs = list(range(2013, 2018))
op = [10.3, 11.2, 12.1, 12.4, 12.7]     # 营业里程（万公里）
dbl = [4.8, 5.7, 6.4, 6.8, 7.2]         # 复线里程
ele = [5.6, 6.5, 7.4, 8.0, 8.7]         # 电气化里程
g17, hsr, dens17, dens_inc = 0.024, 2.5, 132.2, 3.0
dbl_rate17, ele_rate17, west17, west_g = 0.567, 0.685, 5.2, 0.033

print('== 本组自洽检查 ==')
print('12.4×1.024 = %.2f（文字12.7）；复线率 7.2/12.7 = %.2f%%（文字56.7%%）；电化率 8.7/12.7 = %.2f%%（文字68.5%%）'
      % (op[3] * (1 + g17), dbl[4] / op[4] * 100, ele[4] / op[4] * 100))
print('路网密度 132.2/129.2 = %+.2f%%，与营业里程 %+.2f%% 相近（密度与里程同比例变化）' % ((dens17 / (dens17 - dens_inc) - 1) * 100, (op[4] / op[3] - 1) * 100))
assert abs(dbl[4] / op[4] - dbl_rate17) < 0.0005 and abs(ele[4] / op[4] - ele_rate17) < 0.0005
print('未发现矛盾。')

print('\n== 第86题 ==')
print('132.2−3.0 = %.1f -> B；方向弄反 132.2+3.0 = %.1f -> D' % (dens17 - dens_inc, dens17 + dens_inc))

print('\n== 第87题 ==')
inc = west17 * 1e4 / (1 + west_g) * west_g
print('52000/1.033×3.3%% = %.1f 公里 -> A 1661；现期×增速 52000×3.3%% = %.0f -> 最接近B 1761' % (inc, west17 * 1e4 * west_g))

print('\n== 第88题 ==')
r16 = dbl[3] / op[3]
print('2016年复线率 %.2f%%，2017年56.7%%，提高 %.2f 个百分点 -> C 提高2' % (r16 * 100, (dbl_rate17 - r16) * 100))
print('误用电化率：68.5%% − 8.0/12.4 = %.2f 个百分点 -> A 提高4' % ((ele_rate17 - ele[3] / op[3]) * 100))

print('\n== 第89题 ==')
for i in range(1, 5):
    print('  %d年 电气化里程增加 %.1f，增速 %.2f%%' % (yrs[i], ele[i] - ele[i - 1], (ele[i] / ele[i - 1] - 1) * 100))
print('2014年最快 -> A')

print('\n== 第90题（选不正确） ==')
print('A 2013年复线 4.8 < 10.3/2 = %.2f 正确' % (op[0] / 2))
rates = [e / o for e, o in zip(ele, op)]
print('B 电化率 %s 逐年增加 %s 正确' % ([round(r * 100, 1) for r in rates], all(rates[i] > rates[i - 1] for i in range(1, 5))))
print('C 12.7/10.3−1 = %.2f%% 正确' % ((op[4] / op[0] - 1) * 100))
print('D 高铁占比 2.5/12.7 = %.2f%% < 30%% 不正确 -> D' % (hsr / op[4] * 100))
