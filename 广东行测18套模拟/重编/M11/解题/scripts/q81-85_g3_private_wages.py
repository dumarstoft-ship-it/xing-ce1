"""M11 第81—85题（GD2014-XZ-M3，广东城镇私营单位分区域就业人员年平均工资）核算与本组检查。
柱状图按原卷裁图 GD2014-XZ-p10-i02.png 核对数据标签，与转写一致；图题在原卷第10页印于图下（“城镇私营单位”，无“化”）。
原卷材料文字与第96题题干作“城镇化私营单位”，第100题作“从高到底”，编排分别改为“城镇私营单位”“从高到低”。"""

w12 = {'全省': 31920, '珠三角': 34177, '山区': 25017, '东翼': 27626, '西翼': 22386}
w13 = {'全省': 37020, '珠三角': 38868, '山区': 27403, '东翼': 30701, '西翼': 28304}
g13_text, drop_pp = 0.160, 3.9
regions = ['珠三角', '山区', '东翼', '西翼']

print('== 本组检查 ==')
print('全省 37020/31920−1 = %.2f%%（文字16.0%%）；37020/1.16 = %.0f（图31920）' % ((w13['全省'] / w12['全省'] - 1) * 100, w13['全省'] / 1.16))
assert abs(w13['全省'] / w12['全省'] - 1 - g13_text) < 0.0005
print('各区域数值都在全省上下，未发现矛盾（没有权重，无法由区域合成全省）。')

print('\n== 第81题 ==')
print('37020−31920 = %d -> A；按文字 37020×16%%/116%% = %.0f' % (w13['全省'] - w12['全省'], w13['全省'] * 0.16 / 1.16))

print('\n== 第82题 ==')
g = {r: w13[r] / w12[r] - 1 for r in regions}
for r in regions:
    print('  %s 增长 %d，增速 %.2f%%' % (r, w13[r] - w12[r], g[r] * 100))
print('最慢：%s -> B' % min(g, key=g.get))

print('\n== 第83题 ==')
hi, lo = max(regions, key=w12.get), min(regions, key=w12.get)
print('2012年最高%s %d，最低%s %d，倍数 %.3f -> C 1.5' % (hi, w12[hi], lo, w12[lo], w12[hi] / w12[lo]))

print('\n== 第84题 ==')
g12 = g13_text + drop_pp / 100
print('2012年增速 16.0%%+3.9%% = %.1f%%，2011年 31920/1.199 = %.1f -> B 26622' % (g12 * 100, w12['全省'] / (1 + g12)))
print('误把2012年值当2011年 -> D 31920；“回落”理解反用12.1%%：31920/1.121 = %.0f -> 最接近C 28083' % (w12['全省'] / 1.121))

print('\n== 第85题 ==')
w14 = {r: w13[r] * (1 + g[r]) for r in regions}
for r in regions:
    print('  2014年%s ≈ %.0f' % (r, w14[r]))
o14 = sorted(regions, key=lambda r: -w14[r])
print('2014年 %s -> D；2013年顺序 %s（C）；2012年顺序 %s（A）'
      % ('>'.join(o14), '>'.join(sorted(regions, key=lambda r: -w13[r])), '>'.join(sorted(regions, key=lambda r: -w12[r]))))
assert o14 == ['珠三角', '西翼', '东翼', '山区']
