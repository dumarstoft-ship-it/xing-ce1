"""S01 第50题：四根长方体（2×2排列）的四个方向视图。

高度只需相对大小（由题图量得，原图像素）：右前≈95，左后≈131，左前≈164，右后≈204，记为1<2<3<4。
视图每一列：外轮廓取该列最高者；前面的柱子比后面矮时，可见其顶边（一条横线）。
选项读法（左列, 右列），每列记（轮廓高, 内部横线高或None），高度按四档对应：
A 左列(4,线2) 右列(3)；B 左列(4) 右列(3,线2)；C 左列(3) 右列(4,线1)；D 左列(1) 右列(4,线3)
"""
H = {'左前': 3, '右前': 1, '左后': 2, '右后': 4}

def col(near, far):
    hn, hf = H[near], H[far]
    return (max(hn, hf), hn if hn < hf else None)

views = {
 '正面': (col('左前', '左后'), col('右前', '右后')),
 '后面': (col('右后', '右前'), col('左后', '左前')),
 '左面': (col('左后', '右后'), col('左前', '右前')),
 '右面': (col('右前', '左前'), col('右后', '左后')),
}
opts = {'A': ((4, 2), (3, None)), 'B': ((4, None), (3, 2)), 'C': ((3, None), (4, 1)), 'D': ((1, None), (4, 3))}
for k, v in views.items():
    print(k, v, [o for o, w in opts.items() if w == v])
for o, w in opts.items():
    print(o, '是' if w in views.values() else '不是', '某个方向的视图')
