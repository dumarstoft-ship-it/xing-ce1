"""S01 第36题：80名学生，双人间200元/间，三人间270元/间，共7700元且都住满，求住三人间的学生数。
选项 A30 B33 C36 D39"""
sols = [(x, y) for x in range(0, 41) for y in range(0, 27)
        if 2 * x + 3 * y == 80 and 200 * x + 270 * y == 7700]
print('（双人间间数，三人间间数）：', sols)
assert sols == [(25, 10)]
ans = 3 * sols[0][1]
# 人均法：双人间每人100元、三人间每人90元；全住双人间8000元，多出300元，每人差10元 → 30人
assert (80 * 100 - 7700) // (100 - 90) == ans
opts = {'A': 30, 'B': 33, 'C': 36, 'D': 39}
print('三人间学生', ans, '答案：', [k for k, v in opts.items() if v == ans])
