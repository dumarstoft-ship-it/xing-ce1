print('\n== 第78题 ==')
print('1.47/1.59−1 = %.3f%% -> B 下降7.5%%（与2016年比 %.2f%%，与2014年比 %.2f%%，都不在选项中）'
      % ((unit[0] / unit[2] - 1) * 100, (unit[0] / unit[1] - 1) * 100, (unit[0] / unit[3] - 1) * 100))

