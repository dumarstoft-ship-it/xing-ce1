"""S01 第76—80题（GD2019-XZ-M4，A省绿色无公害农业）核算与本组自洽检查。
表格按原卷裁图 GD2019-XZ-p15-i02.png 核对，与转写一致；原卷第15页正文作“农药使用总量580万吨，与2016年相比减少5.69%”
（5.69%与第98题选项的百分数在原卷是嵌入小图），编排改为“5.80万吨”。"""

yrs = [2017, 2016, 2015, 2014]
pest = [5.80, 6.15, 6.28, 6.51]          # 农药使用总量（万吨）
unit = [1.47, 1.56, 1.59, 1.66]          # 单位耕地面积农药使用量（千克/亩）
spyb = [2570, 2561, 2113, 1905]          # “三品一标”总数
new_site = [221, 235, 194, 270]          # 新增申报无公害农产品产地认定
area = [1050, 650, 380, 332]             # 无公害农产品种植面积（万亩）
text = {'农药总量_改前': 580, '农药总量_改后': 5.80, '降幅': 0.0569, '单位用量': 1.47, '新增产地认定': 221,
        '三品一标': 2570, '分项': [1710, 745, 87, 28], '新增绿色食品': 33, '面积': 1050, '产量': 970}

print('== 本组自洽检查与改字核对 ==')
print('表中2017年农药使用总量 %.2f 万吨；改后正文5.80万吨与表一致；5.80/6.15−1 = %.2f%%（正文“减少5.69%%”）'
      % (pest[0], (pest[0] / pest[1] - 1) * 100))
assert abs(pest[0] / pest[1] - 1 + text['降幅']) < 0.00005
print('改前“580万吨”与表差100倍，且580/6.15无意义：改为“5.80万吨”正确。')
print('“三品一标”分项和 %d（正文2570，表2570）；正文221、1050、1.47与表2017年列一致' % sum(text['分项']))
assert sum(text['分项']) == text['三品一标'] == spyb[0]
assert text['新增产地认定'] == new_site[0] and text['面积'] == area[0] and text['单位用量'] == unit[0]
print('未发现矛盾。')

print('\n== 第76题 ==')
