"""S01 第68题：家庭电路。D项“保险丝可以由电阻率大、熔点低的合金制成”——用焦耳定律比较同规格的铅锑合金丝与铜丝。
（A：我国家庭电路是220V交流电；B：金属外壳用电器用三孔插座接地；C：家用电器并联才互不影响。）"""
from math import pi
I, L, d = 10.0, 0.05, 0.5e-3                 # 电流10A，5cm长，直径0.5mm
area = pi * d * d / 4
for name, rho, melt in (('铅锑合金', 2.1e-7, 250), ('铜', 1.7e-8, 1085)):
    R = rho * L / area
    print('%s：电阻%.4fΩ，发热功率I²R=%.2fW，熔点约%d℃' % (name, R, I * I * R, melt))
print('电阻率大→同样电流发热多；熔点低→过载时先熔断，正是保险丝需要的性质，D正确。')
