"""S01 第45题：从第2天起每天比前一天少50千克；从第10天起每天是前一天的一半；第13天10千克，求第1天。
选项 A540 B560 C580 D600"""
d13 = 10
d9 = d13 * 2 ** 4                        # 第10—13天各为前一天的一半：第9天=10×2⁴
d1 = d9 + 50 * 8                         # 第2—9天每天少50，共8次
print('第9天', d9, '第1天', d1)
# 正向模拟检验
x = [None, d1]
for day in range(2, 14):
    x.append(x[-1] - 50 if day < 10 else x[-1] / 2)
print('第1—13天：', x[1:])
assert x[13] == 10 and d1 == 560
opts = {'A': 540, 'B': 560, 'C': 580, 'D': 600}
print('答案：', [k for k, v in opts.items() if v == d1])
print('把第10天也算作“少50”的一天：', d13 * 2 ** 3 + 50 * 9)
