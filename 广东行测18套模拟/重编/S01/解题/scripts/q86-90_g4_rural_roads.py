yrs = list(range(2014, 2019))
total = [388.16, 398.06, 395.98, 400.93, 405]      # 农村公路总里程（万公里，柱）
new = [23, 25.1, 29.3, 28.5, 31.8]                 # 新改建农村公路里程（万公里，折线）
town = [98.08, 98.62, 99.00, 99.39, 99.64]         # 通硬化路面乡镇比例（%）
vill = [99.82, 99.87, 99.94, 99.98, 99.47]         # 通公路建制村比例（%）

print('== 第86题 ==')
print('五年合计 %.1f 万公里 -> D（尾数0+1+3+5+8=17，尾数7）；漏2014年为 %.1f' % (sum(new), sum(new[1:])))

print('\n== 第87题 ==')
inc = {yrs[i]: round(new[i] - new[i - 1], 1) for i in range(1, 5)}
print('较上年增加 %s，最多2016年 -> B；里程最高的是2018年 -> D' % inc)

print('\n== 第88题 ==')
for i in range(1, 5):
    print('  %d年比2014年增加 %.2f' % (yrs[i], total[i] - total[0]))
print('2018年比2014年 16.84 -> C（只有2018年的差等于选项；题干未写比较年份，按最后一年理解）')

print('\n== 第89题 ==')
print('99.64−98.08 = %+.2f 个百分点 -> A 增加1.56；误用2017年 99.64−99.39 = %+.2f -> B' % (town[4] - town[0], town[4] - town[3]))

print('\n== 第90题 ==')
up = lambda v: all(v[i] > v[i - 1] for i in range(1, len(v)))
print('A 新改建逐年增加：%s（2017年28.5<29.3）' % up(new))
print('B 总里程逐年增加：%s（2016年395.98<398.06）' % up(total))
print('C 通硬化路面乡镇比例逐年提高：%s -> C' % up(town))
print('D 通公路建制村比例逐年提高：%s（2018年99.47<99.98）' % up(vill))
