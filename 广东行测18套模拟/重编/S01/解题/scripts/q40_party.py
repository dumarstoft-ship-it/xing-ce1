"""S01 第40题：250名员工，党员比女性非党员多68%，男性非党员不超过100，可能有多少党员。
选项 A67 B75 C116 D126"""
sols = []
for f in range(0, 251):                 # f：女性非党员
    if (f * 168) % 100:
        continue
    p = f * 168 // 100                  # 党员
    m = 250 - p - f                     # 男性非党员
    if 0 <= m <= 100:
        sols.append((p, f, m))
print('（党员，女性非党员，男性非党员）：', sols)
assert [s[0] for s in sols] == [126]
opts = {'A': 67, 'B': 75, 'C': 116, 'D': 126}
print('答案：', [k for k, v in opts.items() if v == sols[0][0]])
# 若把基准弄反（女性非党员比党员多68%）：
rev = [(p, p * 168 // 100, 250 - p - p * 168 // 100) for p in range(0, 251)
       if (p * 168) % 100 == 0 and 0 <= 250 - p - p * 168 // 100 <= 100]
print('基准弄反时（党员，女性非党员，男性非党员）：', rev)
# 忽略“不超过100”时 k=1,2 的情形
print('k=1、2：', [(42 * k, 25 * k, 250 - 67 * k) for k in (1, 2)])
