"""第44题：首场18:00开场，末场22:00开场，9场等间隔，求相邻两场开场间隔。
选项 A25 B30 C35 D40

核验：9 场有 8 个间隔；逐一代入选项，看第9场开场时间是否为 22:00。
"""
options = {"A": 25, "B": 30, "C": 35, "D": 40}
start = 18 * 60
for k, g in options.items():
    last = start + 8 * g
    print(k, g, "第9场开场 %02d:%02d" % divmod(last, 60), "符合" if last == 22 * 60 else "")
print("间隔 = 240 / (9-1) =", 240 / 8)
