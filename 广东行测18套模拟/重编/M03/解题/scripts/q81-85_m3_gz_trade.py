#!/usr/bin/env python3
"""M03 资料分析第3组（第81—85题）：2025年广州市外贸。

用法：python3 q81-85_m3_gz_trade.py
文字材料从 ../../输入/data.json 读取，先核对要用的数字确在原文中，再逐题精确计算。
"""
import json
from pathlib import Path

DATA = Path(__file__).resolve().parents[2] / '输入' / 'data.json'
MID = 'gd-mock-2026h2-s18-m3'

d = json.loads(DATA.read_text(encoding='utf-8'))
m = next(m for m in d['materials'] if m['id'] == MID)
text = m['blocks'][0]['text']

for s in ['进出口总额12407亿元', '同比增长10.4%', '出口额8257亿元，同比增长17.8%',
          '同比分别增长19.2%和28%', '“一带一路”国家进出口增长22.5%',
          '“新三样”产品出口262.5亿元，同比增长68.3%', '电动汽车出口增长70.3%',
          '进口飞机及航材212.5亿元，增量超过90亿元', '市场采购贸易出口109.5亿元，增长39.5%',
          '跨境电商进出口规模超2000亿元', '电动汽车、锂电池、光伏产品', '新业态快速发展',
          '民营企业进出口占全市外贸总值的六成以上', '海外市场发展前景广阔']:
    assert s in text, s
print('材料关键数字/表述均已在原文中找到。')

TOT, gT = 12407.0, 0.104
EXP, gE = 8257.0, 0.178
IMP = TOT - EXP
TOT0, EXP0 = TOT / (1 + gT), EXP / (1 + gE)
IMP0 = TOT0 - EXP0


def pick(value, opts):
    diffs = {k: abs(value - v) for k, v in opts.items()}
    return min(diffs, key=diffs.get), diffs


print('=' * 70)
print('数据整理与自洽检查')
print(f'  2025：总额 {TOT}、出口 {EXP}、进口 {IMP} 亿元')
print(f'  2024：总额 {TOT0:.2f}、出口 {EXP0:.2f}、进口 {IMP0:.2f} 亿元；进口增速 {(IMP/IMP0-1)*100:.3f}%')
print(f'  进口消费品“近1000亿元” < 进口 {IMP:.0f}；飞机及航材212.5 < 进口；无矛盾')
ac0 = 212.5 - 90
print(f'  飞机及航材：增量超过90亿元 ⇒ 2024年不足 {ac0} 亿元，增速超过 {(212.5/ac0-1)*100:.1f}%')

print('=' * 70)
print('第81题  “新三样”= 电动汽车、锂电池、光伏产品 → 无人机不属于 → A')

print('=' * 70)
print('第82题  “跨境电商、市场采购贸易等新业态快速发展”，与“跨境电商发展缓慢”相反 → D')

print('=' * 70)
print('第83题  出口占进出口总额比重的变化（百分点）')
s25 = EXP / TOT * 100
s24 = EXP0 / TOT0 * 100
v83 = s25 - s24
fml = s25 * (gE - gT) / (1 + gE)
print(f'  2025 {s25:.4f}%，2024 {s24:.4f}%，差 {v83:+.4f} 个百分点；公式 现期比重×(a−b)/(1+a) = {fml:+.4f}')
a83, dd = pick(v83, {'A': -4.2, 'B': -3.2, 'C': 4.2, 'D': 3.2})
print(f'  → {a83}  偏差 {dd}')

print('=' * 70)
print('第84题  飞机及航材进口额占商品进口额比重')
v84 = 212.5 / IMP * 100
print(f'  212.5 / (12407−8257) = 212.5/{IMP:.0f} = {v84:.4f}%（若误除以进出口总额：{212.5/TOT*100:.3f}%）')
a84, dd = pick(v84, {'A': 2, 'B': 3, 'C': 4, 'D': 5})
print(f'  → {a84}  偏差 {dd}')

print('=' * 70)
print('第85题  逐项判断')
gI = IMP / IMP0 - 1
print(f'  A 进口增速 = {IMP:.0f}/{IMP0:.2f} − 1 = {gI*100:.3f}%（为负，不是约10.8%）→ 错')
print('  B 电动汽车出口增速70.3% > “新三样”出口增速68.3% ⇒ 比重上升 → 对')
# 用比重公式求上升幅度需要电动汽车出口额，材料未给；只能定性判断，已足够
print(f'  C 一带一路22.5% − 欧盟19.2% = {22.5-19.2:+.1f} 个百分点（高3.3个，不是低5.5个；28−22.5=5.5是与东盟比）→ 错')
inc = 109.5 - 109.5 / 1.395
print(f'  D 市场采购贸易出口增量 = 109.5×39.5%/139.5% = {inc:.4f} 亿元（不到30？{inc < 30}）→ 错')

print('=' * 70)
print('本组答案：', {81: 'A', 82: 'D', 83: a83, 84: a84, 85: 'B'})
