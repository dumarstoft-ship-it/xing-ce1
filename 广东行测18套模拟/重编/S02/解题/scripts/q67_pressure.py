"""S02 第67题：挖掘机装履带的原理。压强p=F/S：对地压力等于重力，不因履带改变；履带增大受力面积，压强减小。
取一台20吨挖掘机比较轮胎着地与履带着地。"""
g, m = 10.0, 20000.0
F = m * g
for name, S in (('4个轮胎着地（每个约0.15m²）', 4 * 0.15), ('两条履带着地（每条约4.0m×0.6m）', 2 * 4.0 * 0.6)):
    print('%s：压力%.0f N，受力面积%.2f m²，压强%.0f Pa' % (name, F, S, F / S))
print('压力不变、压强减小 → A')
