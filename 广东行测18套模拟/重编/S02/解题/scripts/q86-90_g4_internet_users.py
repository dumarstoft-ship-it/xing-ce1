"""S02 第86—90题（SYDW2023-M2，互联网应用用户规模）核算与本组自洽检查。
表格（SYDW2023-p18-i01.png）与年龄结构图（p18-i02.png）按原卷裁图逐项核对，与转写一致；文字与原卷第18页一致。
原卷第96题“下列应用类别1中”、第98题“截止2021年6月”，编排改为“下列应用类别中”“截至2021年6月”；
第99题选项中的“＞”在文字层缺失，渲染第19页核对，四个选项顺序与转写一致。"""

apps = {'即时通信': (98111, 98330, 0.2), '搜索引擎': (76977, 79544, 3.3), '网络新闻': (74274, 75997, 2.3),
        '在线办公': (34560, 38065, 10.1), '网络支付': (85434, 87221, 2.1), '网络购物': (78241, 81206, 3.8),
        '网上外卖': (41883, 46859, 11.9), '在线旅行预定': (34244, 36655, 7.0), '网络视频（含短视频）': (92677, 94384, 1.8),
        '网络直播': (61685, 63769, 3.4), '网络游戏': (51793, 50925, -1.7), '网络音乐': (65825, 68098, 3.5),
        '网约车': (36528, 39651, 8.5), '在线教育': (34171, 32493, -4.9), '在线医疗': (21480, 23933, 11.4)}
netizens, net_g = 10.11, 0.022
age = {'10岁以下': 3.3, '10-19岁': 12.3, '20-29岁': 17.4, '30-39岁': 20.3, '40-49岁': 18.7, '50-59岁': 15.9, '60岁以上': 12.2}

print('== 本组自洽检查 ==')
for k, (a, b, g) in apps.items():
    assert abs((b / a - 1) * 100 - g) < 0.06, k
print('15行增长率都可由两期用户规模复算（误差≤0.05个百分点）')
print('即时通信使用率 %.2f%%（文字97.3%%）；网络视频 %.2f%%（文字93.4%%）；2020年12月网民 %.2f 亿'
      % (98330 / (netizens * 1e4) * 100, 94384 / (netizens * 1e4) * 100, netizens / (1 + net_g)))
print('年龄结构合计 %.1f%%（四舍五入）' % sum(age.values()))

print('\n== 第86题 ==')
inc = {k: apps[k][1] - apps[k][0] for k in ['即时通信', '搜索引擎', '网络新闻', '在线办公']}
print('增长量 %s -> D 在线办公；用户规模最大的是即时通信（A）' % inc)

print('\n== 第87题 ==')
g = {k: b / a - 1 for k, (a, b, _) in apps.items()}
up = [k for k, v in g.items() if v > net_g]
print('增速超过2.2%%（使用率提升）的 %d 项：%s -> A' % (len(up), '、'.join(up)))
print('网络新闻 %.2f%%、网络支付 %.2f%% 紧挨2.2%%；增速为正的共 %d 项（误数为D）' % (g['网络新闻'] * 100, g['网络支付'] * 100, sum(v > 0 for v in g.values())))

print('\n== 第88题 ==')
print('(3.3%%+12.3%%−12.2%%)×10.11 = %.3f 亿 -> B 0.34；漏掉10岁以下 (12.3%%−12.2%%)×10.11 = %.3f -> A'
      % ((age['10岁以下'] + age['10-19岁'] - age['60岁以上']) / 100 * netizens, (age['10-19岁'] - age['60岁以上']) / 100 * netizens))

print('\n== 第89题 ==')
music = netizens * 0.174 * 0.841
edu = netizens * 0.123 * 0.485
news = netizens * 0.203 * 0.834
print('20-29岁网络音乐 %.3f 亿，10-19岁在线教育 %.3f 亿，30-39岁网络新闻 %.3f 亿 -> D 新闻>音乐>教育；只比使用率得B' % (music, edu, news))
assert news > music > edu

print('\n== 第90题（选正确） ==')
sv = 8.88
sv_base = sv / 1.016
non_g = (94384 / 1e4 - sv) / (92677 / 1e4 - sv_base) - 1
print('A 短视频增速1.6%%，网络视频整体1.8%%，非短视频约 %.1f%%：短视频更低 错误' % (non_g * 100))
print('B 网络游戏减少 %d 万，超过一百万 错误' % (51793 - 50925))
print('C 50—59岁直播用户占全体网民 < 15.9%%×73.5%% = %.2f%% < 13%% 正确 -> C' % (15.9 * 0.735))
print('D 40岁以上 %.1f%% < 40岁以下 %.1f%% 错误' % (18.7 + 15.9 + 12.2, 3.3 + 12.3 + 17.4 + 20.3))
