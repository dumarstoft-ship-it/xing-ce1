"""第67题：闭合台灯开关后空气开关跳闸。逐项估算闭合开关后的电流。
家庭电压220V，台灯40W；导线（入户到灯头往返）电阻取0.2～1Ω的量级；空气开关额定电流取16A量级。
"""
U, P = 220.0, 40.0
R_lamp = U ** 2 / P
I_normal = P / U
print(f"灯丝电阻约 {R_lamp:.0f} Ω，正常工作电流约 {I_normal:.2f} A（远小于空气开关额定电流，不会过载）")
for r_wire in (0.2, 0.5, 1.0):
    print(f"  若火线与零线在灯头处直接相碰（导线电阻约{r_wire}Ω）：闭合开关后电流约 {U / r_wire:.0f} A → 短路跳闸")
cases = {
    "A 开关内部短路": ("开关两端被接通，相当于开关一直闭合，灯仍与电源串联", I_normal),
    "B 灯丝断了": ("电路断开", 0.0),
    "C 灯泡处零线与火线接触": ("闭合开关即把火线、零线直接接通（灯头短路）", U / 0.5),
    "D 零线某处接触不良": ("电路断开或电阻增大", 0.0),
}
for k, (desc, I) in cases.items():
    print(f"{k}: {desc}，闭合开关后电流约 {I:.2f} A", "→ 跳闸" if I > 16 else "→ 不跳闸")
