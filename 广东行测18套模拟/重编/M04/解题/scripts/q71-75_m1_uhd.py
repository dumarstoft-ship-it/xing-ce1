#!/usr/bin/env python3
"""M04 资料分析第1组（第71—75题）：广东省超高清视频产业。

用法：python3 q71-75_m1_uhd.py
文字材料从 ../../输入/data.json 读取，先核对要用的数字/表述确在原文中，再逐题精确计算。
"""
import json
from pathlib import Path

DATA = Path(__file__).resolve().parents[2] / '输入' / 'data.json'
MID = 'gd-mock-2026h2-s19-m1'

d = json.loads(DATA.read_text(encoding='utf-8'))
m = next(m for m in d['materials'] if m['id'] == MID)
assert len(m['blocks']) == 1 and m['blocks'][0]['type'] == 'text'
text = m['blocks'][0]['text']

for s in ['建成全国唯一的超高清视频产业发展试验区', '组建国家级制造业创新中心',
          '总投资超4000亿元的一批重大项目落地达产',
          '2025年全省超高清视频产业规模达10803亿元，较2017年增长2.5倍，成为广东第十个万亿级产业集群',
          '全省彩电、手机产量分别占全国的60.3%、44.7%',
          '手机产量同比增长9.4%，较2024年一季度增长4.4%',
          'TCL王牌电器增加值同比增长22.4%', '大疆如影增加值同比增长107.9%',
          '全省投产11条面板线，月产能达105万片，占全国总产能的25%',
          '4K机顶盒用户2905万户，占电视用户总量的89%',
          '全省将聚焦产品端促销、产业链对接、内容制播及AI赋能四大板块']:
    assert s in text, s
assert '8K' not in text and '8k' not in text
print('材料关键数字/表述均已在原文中找到；材料中没有任何“8K”字样。')


def pick(value, opts):
    diffs = {k: abs(value - v) for k, v in opts.items()}
    return min(diffs, key=diffs.get), diffs


print('=' * 70)
print('数据自洽检查：本组为纯文字材料，无分项与合计可对；')
y2017 = 10803 / 3.5
print(f'  2025年10803亿元“较2017年增长2.5倍” ⇒ 2017年 = 10803÷3.5 = {y2017:.2f} 亿元，无矛盾。')

print('=' * 70)
print('第71题  原文：“全省将聚焦产品端促销、产业链对接、内容制播及AI赋能四大板块” → A')

print('=' * 70)
print('第72题  A“全国唯一的试验区”、B“2025年成为第十个万亿级产业集群”、D“国家级制造业创新中心＋总投资超4000亿元”均与原文一致；')
print('        材料只提到4K节目量，未出现8K → C无从推出（说法错误）→ C')

print('=' * 70)
print('第73题  全国面板月产能 = 105 ÷ 25%，全年 = 月产能 × 12')
nat_month = 105 / 0.25
v73 = nat_month * 12
print(f'  全国月产能 {nat_month:.1f} 万片，2026年全年 {v73:.1f} 万片')
a73, dd = pick(v73, {'A': 1260, 'B': 2100, 'C': 3880, 'D': 5040})
print(f'  → {a73}  偏差 {dd}')
print(f'  干扰：A 1260 = 105×12（只算广东）')

print('=' * 70)
print('第74题  设2024年一季度为1：2026年一季度 = 1.044，2025年一季度 = 1.044÷1.094')
r74 = 1.044 / 1.094 - 1
print(f'  2025年一季度同比 = {r74*100:.4f}% ⇒ 下降 {-r74*100:.2f}%（不到5%）→ D')
lo, hi = 1.0435 / 1.0945 - 1, 1.0445 / 1.0935 - 1
print(f'  两个增速各按±0.05个百分点舍入区间：{lo*100:.3f}% ～ {hi*100:.3f}%，结论不变')
assert -0.05 < lo < hi < 0 and -0.05 < r74 < 0

print('=' * 70)
print('第75题')
dA = 107.9 - 22.4
print(f'  A：107.9 − 22.4 = {dA:.1f} 个百分点，不是75.5 → 错')
tv = 2905 / 0.89
print(f'  B：电视用户总量 = 2905 ÷ 89% = {tv:.2f} 万户 > 3000 → 对'
      f'（即使89%由89.5%舍入而来：2905÷0.895 = {2905/0.895:.1f}，仍 > 3000）')
print('  C：只给出彩电、手机产量各占全国的比重，全国彩电、手机产量未知 → 无法比较 → 错')
inc = 10803 - 10803 / 3.5
inc_wrong = 10803 - 10803 / 2.5
print(f'  D：增长2.5倍即2025年是2017年的3.5倍，增长量 = 10803×2.5/3.5 = {inc:.2f} 亿元 > 7500 → 错'
      f'（误把“增长2.5倍”当“是2.5倍”会得 {inc_wrong:.1f} < 7500 而误选D）')
assert tv > 3000 and inc > 7500 and abs(dA - 75.5) > 1
print('  → B')

print('=' * 70)
print('答案：71A 72C 73D 74D 75B')
