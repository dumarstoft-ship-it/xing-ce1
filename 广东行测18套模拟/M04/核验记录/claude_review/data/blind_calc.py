from fractions import Fraction as F


def pct(x):
    return f"{x*100:.4f}%"


def nearest(val, opts, label=""):
    """返回最接近项与各选项差距，用于检查最接近项是否唯一、与相邻选项差得够不够。"""
    diffs = sorted(((abs(val - v), k, v) for k, v in opts.items()))
    best = diffs[0]
    second = diffs[1]
    print(f"  {label} 计算值={val:.6g}；最接近 {best[1]}={best[2]}（差{best[0]:.4g}），"
          f"次近 {second[1]}={second[2]}（差{second[0]:.4g}），次近/最近差距比="
          f"{(second[0]/best[0]) if best[0] else float('inf'):.2f}")
    return best[1]


