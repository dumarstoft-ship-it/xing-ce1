"""第二阶段补充复算：干扰项对应的错法、口径变体（只用材料数值）。"""
from fractions import Fraction as F
f = lambda x, n=3: "%.*f" % (n, float(x))
print("86 用水人口口径：704.88÷(113.33÷20×99.57%) =", f(F(70488, 100) / (F(11333, 100) / 20 * F(9957, 10000))), "→ 仍 C 124")
print("86 上年人口口径：704.88÷(113.33÷1.0112÷19.72) =", f(F(70488, 100) / (F(11333, 100) / F(10112, 10000) / F(1972, 100))), "→ 仍 C")
print("87 误用道路长度增速1.36%：99.36÷1.0136 =", f(F(9936, 100) / F(10136, 10000)), "→ B 98")
print("87 误用供水管道：119.95÷1.0402 =", f(F(11995, 100) / F(10402, 10000)), "→ D 115")
print("81 '重复还原基期'错法：829.6÷(1−3.8%) =", f(F(8296, 10) / F(962, 1000)), "→ 仍最近 A 861.1（与 B 865.7 差", f(F(8657, 10) - F(8296, 10) / F(962, 1000)), "）")
print("79 现期比 270710÷143487 =", f(F(270710, 143487), 4), "；2024年9月 30853÷16271 =", f(F(30853, 16271), 4),
      "；2023年9月 29835÷16326 =", f(F(29835, 16326), 4), "→ 均最近 B 1.89")
print("88 只看在建总长：4802.89→5061.32→4121.13 先升后降；只看城市数 44→45→38（平均长度与之无单调对应）")
print("89 误看无害化处理率+0.01个百分点 → A；误用 6.87%−3.05%=3.82 → 仍 B")
print("84 误以内资整体为基准：811.4÷1.227 =", f(F(8114, 10) / F(1227, 1000), 2), "→ A 661.3")
print("83 误用 811.4×(26.4%−20.9%) =", f(F(8114, 10) * F(55, 1000), 2), "→ A 低不到70")
print("80 A 若分母误用运输工具总数：(2795972−360315)÷(3555116−451265) =", f(F(2795972 - 360315, 3555116 - 451265) * 100, 2), "%")
print("80 C 若分母误用进出境总数增量：29772÷413997 =", f(F(29772, 413997) * 100, 2), "%")
print("80 非进出境 9月 =", 3555116 - 3283126, "；1—9月月均 =", f(F(2430122, 9), 0), "；2023年9月 =", (3555116 - 451265) - (3283126 - 413997),
      "；2023年1—9月月均 =", f(F(31896977 - 7531496 - (29466855 - 7163173), 9), 0))
