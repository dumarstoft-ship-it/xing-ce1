def norm(s):
    return re.sub(r"\s+", "", s)


def main():
    pages = {}
    with open(BOOK, encoding="utf-8") as f:
        for line in f:
            if line.strip():
                r = json.loads(line)
                pages[r["pdf_page"]] = norm(r["text"])
    sel = {q["number"]: q for q in json.loads(SEL.read_text(encoding="utf-8"))}
    out = []
    for n in range(1, 16):
        cited = sel[n]["provenance"]["book_pages"]
        print(f"\n=== 第{n}题  所引讲义页 {cited}")
        qres = {"number": n, "cited_pages": cited, "claims": []}
        for label, variants in CLAIMS[n]:
            hit_cited, hit_other = set(), set()
            for v in variants:
                nv = norm(v)
                for p, t in pages.items():
                    if nv in t:
                        (hit_cited if p in cited else hit_other).add(p)
            if hit_cited:
                status = "所引页命中"
            elif hit_other:
                status = "仅讲义其他页命中"
            else:
                status = "讲义中无"
            print(f"  [{status}] {label}  所引页:{sorted(hit_cited) or '-'}  其他页:{sorted(hit_other) or '-'}")
            qres["claims"].append({"label": label, "variants": variants, "status": status,
                                   "cited_hits": sorted(hit_cited), "other_hits": sorted(hit_other)})
        out.append(qres)
    (HERE / "provenance_page_check.out.json").write_text(
        json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    print("\n已写出", HERE / "provenance_page_check.out.json")


if __name__ == "__main__":
    main()
