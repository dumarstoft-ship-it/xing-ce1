def clean_stem(s):
    s = s.replace('\r','').strip()
    if '![' in s:
        return s
    s = re.sub(r'\n+', '', s)
    s = re.sub(r'(?<=[。；])(?=(?:根据|以下|由此|下列|要使|关于))', '\n', s)
    s = re.sub(r'(?=[（(][1-9][）)])', '\n', s)
    # Restore clearly delineated speakers, not incidental uses of the names.
    s = re.sub(r'(?<!\n)(?=[甲乙丙丁][:：])', '\n', s)
    return s.strip()

