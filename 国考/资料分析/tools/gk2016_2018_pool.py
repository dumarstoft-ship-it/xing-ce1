def closest(value, options):
    """数值选项：取最接近的一项（返回字母）。"""
    best = min(range(4), key=lambda i: abs(options[i] - value))
    return "ABCD"[best]


def which(flags):
    """逐项判断题：恰好一项为真，返回其字母。"""
    hit = [k for k, f in zip("ABCD", flags) if f]
    assert len(hit) == 1, flags
    return hit[0]


def pct(a, b):
    return a / b - 1


