TYPES = ("比较排序", "比重", "增长量", "增长率", "现期量与简单计算", "基期量", "倍数", "平均数", "综合分析判断", "材料理解", "图形选项")


def load(pid):
    return [json.loads(l) for l in open(BANK / f"{pid}.jsonl", encoding="utf-8") if l.strip()]


def selfcheck(pid, rows):
    assert len(rows) == 20, pid
    assert [r["question_number"] for r in rows] == list(range(111, 131)), pid
    mats = {}
    for r in rows:
        assert r["id"] == f"{pid}-Q{r['question_number']:03d}" and r["paper_id"] == pid
        assert r["section"] == "资料分析" and r["question_type"] == "single_choice"
        assert [o["label"] for o in r["options"]] == list("ABCD"), r["id"]
        for o in r["options"]:
            assert o["text"] or o["image_refs"], (r["id"], o["label"])
        a = r["answer"]
        assert a["status"] == "known" and len(a["values"]) == 1 and len(a["values"][0]) == 1, r["id"]
        assert a["values"][0][0] in "ABCD" and a["source_pages"], r["id"]
        mats.setdefault(r["material"]["id"], []).append(r["question_number"])
        assert r["question_number"] in r["material"]["question_numbers"], r["id"]
    assert len(mats) == 4 and all(len(v) == 5 for v in mats.values()), (pid, mats)
    for r in rows:
        assert r["material"]["question_numbers"] == mats[r["material"]["id"]], r["id"]
    manifest = {m["id"]: m for m in json.load(open(BANK / "assets" / pid / "manifest.json", encoding="utf-8"))}
    used = set()
    for r in rows:
        blocks = [b for b in r["material"]["content"] if b["type"] == "image"] + r["figures"]
        for b in blocks:
            p = BANK / b["path"]
            assert p.exists(), p
            assert hashlib.sha256(p.read_bytes()).hexdigest() == manifest[b["image_id"]]["sha256"], p
            used.add(b["image_id"])
        for o in r["options"]:
            for ref in o["image_refs"]:
                assert ref["image_id"] in {f["image_id"] for f in r["figures"]}, r["id"]
    assert used == set(manifest), (pid, set(manifest) - used)
    return mats, len(manifest)


def main():
    records, groups, summary = [], [], []
    for pid in PAPERS:
        rows = load(pid)
        mats, nimg = selfcheck(pid, rows)
        key = {r["question_number"]: r["answer"]["values"][0][0] for r in rows}
        got = SOLVERS[pid]()
        bad = {n: (got.get(n), key[n]) for n in key if got.get(n) != key[n]}
        if bad:
            sys.exit(f"{pid} 核算与来源答案不一致：{bad}")
        R = RATINGS[pid]
        for r in rows:
            n = r["question_number"]
            t, mode, sec, chk, heavy, basis = R[n]
            assert t in TYPES and mode in MODES and (heavy in MODES or heavy is None), (pid, n)
            assert (t == "综合分析判断") == (chk is not None), (pid, n)
            records.append({
                "id": r["id"], "paper": pid, "number": n, "section": "资料分析", "part": "资料分析",
                "material_id": r["material"]["id"], "dup_of": None, "type": t, "mode": mode, "est_seconds": sec,
                "options_to_check": chk, "heaviest_option_mode": heavy, "issues": ISSUES[pid].get(n, []), "excluded": None})
        for mid, qnums in mats.items():
            k = int(mid.rsplit("-M", 1)[1])
            sec, form, region, note, issues = GROUPS[pid][k]
            groups.append({"paper": pid, "material_id": mid, "material_seconds": sec,
                           "questions": [f"{pid}-Q{n:03d}" for n in qnums], "material_form": form, "region": region,
                           "material_note": note, "dup_of": None, "issues": issues, "excluded": None})
            cnt = {m: sum(R[n][1] == m for n in qnums) for m in MODES}
            summary.append((mid, len(qnums), cnt, sec, sum(R[n][2] for n in qnums)))
        print(f"{pid}: 20题、4组、{nimg}张图自检通过；核算答案与来源答案全部一致")
    POOL.write_text(json.dumps(records + groups, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"写出 {POOL.relative_to(REPO)}：{len(records)}题、{len(groups)}组")
    for mid, n, cnt, msec, qsec in summary:
        dist = "、".join(f"{m}{c}" for m, c in cnt.items() if c)
        print(f"  {mid}: {n}题（{dist}），材料{msec}秒，作答合计{qsec}秒")


if __name__ == "__main__":
    main()
