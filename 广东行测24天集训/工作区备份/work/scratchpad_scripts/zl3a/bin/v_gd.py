from vlib import *
R = {}

# ---------------- GD2015X (三) 珠江水系客货运输量（表，季度） ----------------
fr13, fr14 = [1.4, 1.5, 1.6, 1.7], [1.6, 1.7, 1.9, 1.9]              # 货运量 亿吨
ft13, ft14 = [288, 322.6, 342.4, 397.9], [312.9, 338.8, 367.9, 442.5]  # 货运周转量 亿吨公里
pa13, pa14 = [342, 370, 442, 442], [335, 387, 443, 440]               # 客运量 万人
pt13, pt14 = [1.9, 2, 2.3, 2.3], [1.9, 2.1, 2.3, 2.3]                 # 客运周转量 亿人公里
d = sum(fr14) - sum(fr13); k, m = nearest(d, {'A': 0.5, 'B': 0.9, 'C': 1.2, 'D': 1.7})
R['GD2015X-96'] = dict(ans=k, margin=m, calc=f"货运量2014年合计{sum(fr14):.1f}−2013年{sum(fr13):.1f}={d:.1f}亿吨→B（逐季差0.2+0.2+0.3+0.2）。")
dif = [b - a for a, b in zip(pa13, pa14)]
qmax = max(range(4), key=lambda i: abs(dif[i]))
R['GD2015X-97'] = dict(ans='ABCD'[qmax], margin=None, calc=f"客运量逐季差（2014−2013）：{dif}，绝对值最大是二季度（+17）→B；一季度−7是“减少最多”，不是相差最大。")
g = [gr(b, a) for a, b in zip(ft13, ft14)]
hi, lo = max(range(4), key=lambda i: g[i]), min(range(4), key=lambda i: g[i])
assert (hi, lo) == (3, 1)
R['GD2015X-98'] = dict(ans='D', margin=(g[2] - g[1]) / g[2],
    calc='货运周转量各季增速：' + '，'.join(f'{i+1}季度{f(g[i],2)}%' for i in range(4)) + '→最高四季度、最低二季度D。四季度增量44.6约为一季度24.9的1.8倍，而基数397.9只是288的1.38倍，故四季度>一季度；二、三季度基数接近，增量16.2<25.5，二季度更低。')
ann = {'货运量': gr(sum(fr14), sum(fr13)), '货运周转量': gr(sum(ft14), sum(ft13)), '客运量': gr(sum(pa14), sum(pa13)), '客运周转量': gr(sum(pt14), sum(pt13))}
lo = min(ann, key=ann.get)
assert lo == '客运量'
R['GD2015X-99'] = dict(ans='C', margin=(ann['客运周转量'] - ann['客运量']) / ann['客运周转量'],
    calc='全年增速：' + '，'.join(f'{n}{f(ann[n],2)}%' for n in ann) + '→客运量最低C。不同单位的指标比增速只看“增量÷基期”：客运量9÷1596<客运周转量0.1÷8.5。')
dft = [b - a for a, b in zip(ft13, ft14)]
assert ann['客运周转量'] < 2 and max(range(4), key=lambda i: abs(dif[i])) == 1 and min(range(4), key=lambda i: dft[i]) == 1 and pa14[2] > pa14[3]
R['GD2015X-100'] = dict(ans='C', margin=(2 - ann['客运周转量']) / 2,
    calc=f"C：客运周转量全年8.5→8.6，增速{f(ann['客运周转量'],2)}%<2%→正确。A：客运量相差最大是二季度→错。B：货运周转量逐季增量{[round(x,1) for x in dft]}，相差最小是二季度→错。D：2014年客运量最高在三季度（443>440）→错。答案C。")

# ---------------- GD2016Z (二) 2010-2014年新型农村合作医疗（表，年份倒序排列） ----------------
Y = [2014, 2013, 2012, 2011, 2010]
cnty = dict(zip(Y, [2854, 2853, 2852, 2853, 2856])); open_ = dict(zip(Y, [2349, 2489, 2566, 2637, 2678]))
part = dict(zip(Y, [7.36, 8.02, 8.05, 8.32, 8.36])); rate = dict(zip(Y, [98.9, 99.0, 98.3, 97.5, 96.0]))
perc = dict(zip(Y, [410.89, 370.59, 308.50, 246.21, 156.60])); fund = dict(zip(Y, [2890.40, 2908.00, 2408.00, 1710.19, 1187.80]))
ben = dict(zip(Y, [16.52, 19.42, 17.45, 13.15, 10.87]))
gf = {y: gr(fund[y], fund[y - 1]) for y in (2011, 2012, 2013, 2014)}
o, _ = rank_margin(gf)
assert o[0] == 2011
R['GD2016Z-91'] = dict(ans='A', margin=(gf[2011] - gf[2012]) / gf[2011],
    calc='基金支出增速：' + '，'.join(f'{y}年{f(gf[y],2)}%' for y in sorted(gf)) + '→2011年最高A；2012年40.8%是最强竞争项（增量698对1710，2011年522对1188）。注意表格年份从左到右是2014→2010倒序。')
sh = {y: open_[y] / cnty[y] * 100 for y in Y}
cnt = [y for y in Y if sh[y] > 90]
assert sorted(cnt) == [2010, 2011]
R['GD2016Z-92'] = dict(ans='B', margin=abs(sh[2012] - 90) / 90,
    calc='开展县数÷县级区划数：' + '，'.join(f'{y}年{f(sh[y],3)}%' for y in sorted(sh)) + f'；超过90%的只有2010、2011年→B。2012年2566÷2852={f(sh[2012],3)}%，比90%只低0.03个百分点（2852×0.9=2566.8>2566），必须精算。')
gb = {y: gr(ben[y], ben[y - 1]) for y in (2011, 2012, 2013, 2014)}
o, _ = rank_margin(gb)
assert o[0] == 2012
R['GD2016Z-93'] = dict(ans='B', margin=(gb[2012] - gb[2011]) / gb[2012],
    calc='受益人次增速：' + '，'.join(f'{y}年{f(gb[y],2)}%' for y in sorted(gb)) + '→2012年最高B（4.30÷13.15，首位商3）。')
assert fund[2014] < fund[2013] and min(part, key=part.get) == max(perc, key=perc.get) == 2014 and max(rate, key=rate.get) == 2013 and max(part, key=part.get) == 2010
R['GD2016Z-95'] = dict(ans='A', margin=None,
    calc='A：2014年基金支出2890.40<2013年2908.00，不是逐年增加→说法有误，选A。B：参加人数最少（7.36亿）与人均筹资最多（410.89元）都是2014年→对。C：参与率最高99.0%在2013年→对。D：参加人数最多8.36亿在2010年→对。')

# ---------------- GD2014Z (材料2) 2013年广东货运（表） ----------------
modes = ['铁路', '公路', '水路', '航空', '管道']
vol = dict(zip(modes, [(12048, 0.4), (217643, 15.1), (68340, 18.4), (131, 2.7), (7668, 2.8)]))           # 货运量 万吨, 增速%
tkm = dict(zip(modes, [(301.59, -1.5), (2872.31, 18), (9019.14, 32.2), (44.14, 4.1), (169.91, -3.9)]))    # 周转量 亿吨公里, 增速%
assert sum(v[0] for v in vol.values()) == 305830 and abs(sum(v[0] for v in tkm.values()) - 12407.08) < 0.05
v = 12407.08 / 1.269; k, m = nearest(v, {'A': 8907, 'B': 9777, 'C': 10198, 'D': 11764})
R['GD2014Z-93'] = dict(ans=k, margin=m, calc=f"12407.08÷1.269={f(v,0)}亿吨公里→B。选项首位相同、第二位不同，截三位直除（12407÷1.27≈9.77千）即可；原解析易错项C。")
both = [n for n in modes if vol[n][1] > 15 and tkm[n][1] > 15]
assert both == ['公路', '水路']
R['GD2014Z-94'] = dict(ans='A', margin=(15.1 - 15) / 15,
    calc='两列增速同时>15%：公路（15.1%、18%）、水路（18.4%、32.2%）→A。公路货运量15.1%只比线高0.1个百分点；航空4.1%、管道−3.9%在周转量一列就出局。')
w12v = base(68340, 18.4) / base(305830, 14.8) * 100; w12t = base(9019.14, 32.2) / base(12407.08, 26.9) * 100
w13v = 68340 / 305830 * 100; w13t = 9019.14 / 12407.08 * 100
k, m = nearest(w12t - w12v, {'A': 52, 'B': 46, 'C': 50, 'D': 48})
R['GD2014Z-95'] = dict(ans=k, margin=m, calc=f"2012年水路占比：货运量{f(w12v,2)}%（=68340/1.184÷305830/1.148），周转量{f(w12t,2)}%（=9019.14/1.322÷12407.08/1.269），低{f(w12t-w12v,2)}个百分点→D 48。若直接用2013年数据：{f(w13v,2)}%与{f(w13t,2)}%，差{f(w13t-w13v,2)}，落到C 50（原解析易错项C，正确率仅26%）。")
up_t = [n for n in modes if tkm[n][1] > 26.9]; up_wrong = [n for n in modes if tkm[n][1] > 14.8]
sh13 = {n: tkm[n][0] / 12407.08 for n in modes}; sh12 = {n: base(*tkm[n]) / base(12407.08, 26.9) for n in modes}
up_exact = [n for n in modes if sh13[n] > sh12[n]]
assert up_t == up_exact == ['水路'] and up_wrong == ['公路', '水路']
R['GD2014Z-94V'] = dict(ans='A', margin=(32.2 - 26.9) / 32.2,
    calc='改编题核算：周转量比重上升⇔该运输业周转量增速>全省周转量增速26.9%。只有水路32.2%满足（铁路−1.5%、公路18%、航空4.1%、管道−3.9%都低于26.9%）→1个，A。逐项精算比重：' + '，'.join(f'{n}{f(sh12[n]*100,2)}%→{f(sh13[n]*100,2)}%' for n in modes) + '，只有水路上升，唯一。误把全省货运量增速14.8%当基准会数出公路、水路2个（B）。')

# ---------------- GD2014Z (材料3) 2012-2013年广东城镇私营单位分区域年平均工资（柱状图） ----------------
reg = {'全省': (31920, 37020), '珠三角': (34177, 38868), '山区': (25017, 27403), '东翼': (27626, 30701), '西翼': (22386, 28304)}
