def fix(text):
    return '\n'.join(norm(l) for l in text.split('\n') if l.strip())
def write(mid, users):
    s=MATS[mid]; im,text,f=build(mid, write=True)
    text=fix(text)
    ex=EXTRA.get(mid,{})
    if ex.get('tail'): text=text+'\n'+ex['tail']
    pid=PAPER.get(s['tag'], s['tag'])
    pages=sorted({p+1 for p,_,_ in s['segs']})
    m=dict(mid=mid, source=dict(paper=pid, file=f, pages=pages, segs_0based=s['segs'], version_note=s['vnote']),
           text=text, assets=[f'zl_materials/{mid}/{mid}.png'], transcription=ex.get('tr'),
           notes=f"建档：ZL2B（2026-11-08，D05保留块）。截图由原PDF按页坐标裁切（200dpi），只遮去页眉页脚、页码和店铺水印行，内容像素未改。表/图数值另有编者转录（transcription），只供检索核对，以截图为准。"+(NOTES.get(mid,'')+'' if NOTES.get(mid) else '')+f" ZL2B 使用本材料的题：{users}")
    json.dump(m, open(f'{ROOT}/{mid}/material.json','w'), ensure_ascii=False, indent=1)
    return m
