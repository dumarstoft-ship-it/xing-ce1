"""ZL2A independent verification: every question recomputed from material numbers.
Each entry: key -> dict(ans=<computed letter>, margin=<relative gap that decides the answer>, calc=<notes text>).
margin = how far the decisive quantity sits from the nearest wrong option / interval boundary / competing item,
relative to the quantity itself (used to set precision_need)."""
import json

def inc(cur, r):          # increment from current value and growth rate (r in %)
    return cur * r / (100 + r)
def base(cur, r):
    return cur / (1 + r / 100)
def f(x, n=2):
    return f'{x:.{n}f}'
def nearest(v, opts):
    """opts: dict letter->number; returns (best letter, rel gap to the nearest wrong option)."""
    best = min(opts, key=lambda k: abs(opts[k] - v))
    others = [abs(opts[k] - v) for k in opts if k != best]
    return best, (min(others) - abs(opts[best] - v)) / abs(v)
def interval(v, bounds):
    """bounds: list of (letter, lo, hi); returns letter and rel distance to the nearest boundary."""
    for k, lo, hi in bounds:
        if lo <= v < hi:
            d = min(abs(v - lo) if lo > -1e17 else 1e18, abs(hi - v) if hi < 1e17 else 1e18)
            return k, d / abs(v)
    raise ValueError(v)
