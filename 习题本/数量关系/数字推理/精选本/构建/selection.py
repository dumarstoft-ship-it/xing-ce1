def main():
    out, rec_path = sys.argv[1], sys.argv[2]
    recs = {r["id"]: r for r in json.load(open(rec_path))}
    ids = [q["id"] for m in MODULES for g in m["groups"] for q in g["questions"]]
    assert len(ids) == len(set(ids)), "选题重复"
    for i in ids: assert i in recs and not recs[i]["selfmade"], i
    bk = [b for m in MODULES for b in m.get("backup", [])]
    assert not set(bk) & set(ids), set(bk) & set(ids)
    for b in bk: assert b in recs, b
    tiers = Counter(q["tier"] for m in MODULES for g in m["groups"] for q in g["questions"])
    nmodels = sum(1 for m in MODULES for g in m["groups"] if g.get("id"))
    SEL["subtitle"] = f"{len(ids)} 道精选真题 · {nmodels} 个模型 · 从 249 题中挑出"
    SEL["cover"]["stats"] = (f"原书249题 → 本册{len(ids)}题，全部真题：核心 {tiers['核心']}、进阶 {tiers['进阶']}。另列加练备选 {len(bk)} 题，"
                             f"只给原书编号和页码。题目和解析从原书原样裁出，编号沿用原书，如 M01-04 指模型 M01 的第4题。")
    def cnt(pred): return sum(1 for i in ids if pred(recs[i]))
    parts = [("模型页（30个模型）", lambda r: r["family"] != "跨模型", "83道自拟变式；同一模型里数字结构相同的真题；规律一眼可见的入门题"),
             ("入册诊断", lambda r: r["section"] == "入册诊断", "与模型页重复的基础题"),
             ("辨型", lambda r: r["section"].startswith("辨型"), "与模型页动作相同的题；题面有瑕疵的题"),
             ("混合", lambda r: r["section"].startswith("混合"), "与模型页或辨型重复的题"),
             ("攻难盲测", lambda r: r["section"].startswith("攻难"), "规则偏、只有两行可验或选项有缺陷的题"),
             ("基础回补", lambda r: r["section"] == "基础回补", "基础步长与公比，熟练者可跳过")]
    SEL["appendix"]["table"] = [[n, sum(1 for r in recs.values() if f(r)), cnt(f), why] for n, f, why in parts]
    json.dump(SEL, open(out, "w"), ensure_ascii=False, indent=1)
    print(f"{len(ids)} 题（{dict(tiers)}），{nmodels} 个模型，备选 {len(bk)}")
    print([(t[0], t[1], t[2]) for t in SEL["appendix"]["table"]])

if __name__ == "__main__":
    main()
